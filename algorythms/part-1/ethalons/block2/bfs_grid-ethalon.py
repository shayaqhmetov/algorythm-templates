# shortest_path — LeetCode 1091, Shortest Path in Binary Matrix
# ВАРИАНТ В: кратчайший путь из точки в точку
#
# УСЛОВИЕ
#     Квадратная сетка n x n из 0 (проходимо) и 1 (стена).
#     Пройти из левого верхнего угла в правый нижний, двигаясь в ЛЮБУЮ из
#     8 сторон (включая диагонали).
#     Вернуть длину пути В КЛЕТКАХ (стартовая и конечная включены).
#     Пути нет — вернуть -1.
#
# ПРИМЕР
#     grid = [[0,0,0],
#             [1,1,0],
#             [1,1,0]]
#     -> 4   (путь: (0,0) -> (0,1) -> (1,2) -> (2,2), считаем клетки)
#
#     grid = [[0,1],
#             [1,0]]
#     -> 2   (по диагонали за один шаг)
#
# ВОСЕМЬ НАПРАВЛЕНИЙ
#     Единственное отличие от обычной сетки — DIRS8 вместо DIRS4.
#     Всегда перечитывай условие: "по горизонтали и вертикали" -> 4,
#     "в любую сторону / включая диагонали" -> 8. Перепутать легко.
#
# ПОЧЕМУ ПРОВЕРКА ЦЕЛИ ПРИ ИЗВЛЕЧЕНИИ
#     Как только клетка вышла из очереди, расстояние до неё уже финальное:
#     BFS не может найти к ней путь короче позже. Поэтому return сразу.
#
# ЛОВУШКА С ЕДИНИЦЕЙ
#     dist стартует с 1, а не с 0, потому что считаем КЛЕТКИ, а не переходы.
#     Отдельно проверяем старт и финиш: если хоть один — стена, ответ -1
#     ещё до запуска BFS.
#     Вход 1x1 из одного нуля даёт 1 — это ловит обе ошибки сразу.
# =============================================================================

def shortest_path(grid):
    n = len(grid)
    if n == 0 or grid[0][0] == 1 or grid[n - 1][n - 1] == 1:
        return -1

    q = deque([(0, 0)])
    seen = {(0, 0)}
    dist = 1                                # считаем клетки, старт уже один

    while q:
        for _ in range(len(q)):             # один слой волны
            r, c = q.popleft()
            if r == n - 1 and c == n - 1:   # дошли — расстояние финальное
                return dist
            for dr, dc in DIRS8:
                nr, nc = r + dr, c + dc
                if (0 <= nr < n and 0 <= nc < n
                        and grid[nr][nc] == 0
                        and (nr, nc) not in seen):
                    seen.add((nr, nc))
                    q.append((nr, nc))
        dist += 1

    return -1


