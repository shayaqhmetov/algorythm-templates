"""
ШАБЛОН 6 — TOPOLOGICAL SORT (алгоритм Кана)

ЧТО ЭТО
    Есть задачи с зависимостями: A нельзя начать, пока не сделан B.
    Топологическая сортировка — порядок, в котором можно всё выполнить,
    ни разу не нарушив зависимость.
    Работает только на ОРИЕНТИРОВАННОМ графе БЕЗ ЦИКЛОВ.
    Есть цикл (A ждёт B, B ждёт A) — валидного порядка не существует.

    Слова-маркеры: "предварительные требования", "порядок курсов",
    "порядок сборки", "зависимости пакетов", "можно ли выполнить все".

БОНУС, РАДИ КОТОРОГО ЕГО ЧАСТО И БЕРУТ
    Кан заодно ДЕТЕКТИТ ЦИКЛ бесплатно: если в результат попали не все
    вершины, значит остаток замкнут в кольцо.
    Поэтому задача "есть ли цикл в ориентированном графе" решается
    этим же кодом, без отдельного алгоритма с тремя цветами.

INDEGREE — ЕДИНСТВЕННОЕ НОВОЕ ПОНЯТИЕ
    indegree[v] — сколько рёбер ВХОДИТ в v, то есть скольких предшественников
    ещё надо выполнить перед v.
    indegree == 0 значит "готово к выполнению прямо сейчас".

СКЕЛЕТ (это и есть то, что заучивается)

    adj = [[] for _ in range(n)]
    indegree = [0] * n
    for a, b in edges:                 # ребро a -> b, значит a раньше b
        adj[a].append(b)
        indegree[b] += 1               # растёт у КОНЦА ребра

    q = deque(v for v in range(n) if indegree[v] == 0)   # всё, что готово сразу
    order = []

    while q:
        v = q.popleft()
        order.append(v)
        for u in adj[v]:
            indegree[u] -= 1           # v выполнен, одной зависимостью меньше
            if indegree[u] == 0:       # у u больше нет долгов -> в очередь
                q.append(u)

    return order if len(order) == n else []   # не все -> был цикл

КАК ЭТО РАБОТАЕТ НА ПАЛЬЦАХ
    Кладём в очередь всё, у чего нет входящих зависимостей — это можно делать
    хоть сейчас. Выполняем задачу, вычёркиваем её из долгов у всех,
    кто её ждал. У кого долгов не осталось — тот встаёт в очередь следующим.
    Так волна и катится по графу.

    Это тот же BFS: deque, popleft, "готовые" вместо "непосещённых".
    Единственное отличие — вершина попадает в очередь не когда её УВИДЕЛИ,
    а когда у неё обнулился счётчик долгов.

ПЯТЬ МЕСТ, ГДЕ ОШИБАЮТСЯ
    1. НАПРАВЛЕНИЕ РЕБРА. Самая частая ошибка, и она молчаливая.
       Всегда выписывай явно: "[a, b] означает, что ... раньше ...".
       В LeetCode 207 пары идут ЗАДОМ НАПЕРЁД: [a, b] значит b перед a,
       то есть ребро b -> a. Перепутал — получишь ровно обратный порядок.
    2. indegree растёт у КОНЦА ребра (у того, кто ждёт), а не у начала.
    3. Проверка len(order) == n в конце. Без неё цикл вернёт частичный
       порядок и промолчит.
    4. adj и indegree — списки длины n, а не словари: вершины без рёбер
       обязаны попасть в результат, а в edges их нет.
    5. indegree уменьшается ВНУТРИ цикла по соседям, а не один раз.

ОТВЕТ НЕ ЕДИНСТВЕННЫЙ
    Валидных порядков обычно несколько. Поэтому тесты ниже проверяют
    не точный список, а ВАЛИДНОСТЬ порядка — через is_valid_order().
    На интервью это же и стоит проговорить: "порядков много, вернём любой".

ПОРЯДОК ДРИЛЛА (5 минут)
    В сессию берёшь ОДНУ функцию.
    Ротация: 1) topo_order  2) can_finish  3) topo_order_dfs
             4) min_semesters.
    can_finish — это topo_order с выброшенным списком, но с ПЕРЕВЁРНУТЫМ
    направлением рёбер. Дриллится отдельно именно ради направления.
    topo_order_dfs — тот же ответ другим алгоритмом, через три цвета:
    его просят фразой "а теперь через DFS".
    min_semesters — Кан по слоям, как счёт уровней в BFS.

ПРИЗНАК, ЧТО ШАБЛОН СЕЛ
    Пять строк построения (adj, indegree, стартовая очередь) выходят подряд
    без пауз, а думаешь только над тем, куда смотрит ребро.
"""

from collections import deque


# =============================================================================
# topo_order — базовая конструкция, алгоритм Кана
#
# УСЛОВИЕ
#     Дано: n вершин 0..n-1 и список ориентированных рёбер.
#           Ребро [a, b] означает: a должен идти РАНЬШЕ b.
#     Вернуть: любой валидный топологический порядок (список всех n вершин).
#              Если есть цикл — пустой список.
#
# ПРИМЕР
#     n = 4, edges = [[0,1], [0,2], [1,3], [2,3]]
#
#         0 -> 1
#         |    |
#         v    v
#         2 -> 3
#
#     -> [0, 1, 2, 3]   (валиден также [0, 2, 1, 3])
#
#     indegree на старте: [0, 1, 1, 2]
#     в очереди только 0 — остальные кого-то ждут
#
#     берём 0 -> у 1 и 2 долги обнулились -> очередь [1, 2]
#     берём 1 -> у 3 остался 1 долг       -> очередь [2]
#     берём 2 -> у 3 долгов не осталось   -> очередь [3]
#     берём 3 -> order = [0, 1, 2, 3], длина 4 = n, цикла нет
#
#     n = 2, edges = [[0,1], [1,0]] -> []
#         оба ждут друг друга, indegree ни у кого не ноль,
#         очередь пуста с самого начала, order = [] -> цикл
# =============================================================================

def topo_order(n, edges):
    adj = [[] for _ in range(n)]            # списки длины n, а не словари
    indegree = [0] * n

    for a, b in edges:                      # a раньше b, значит ребро a -> b
        adj[a].append(b)
        indegree[b] += 1                    # растёт у КОНЦА ребра

    q = deque(v for v in range(n) if indegree[v] == 0)
    order = []

    while q:
        v = q.popleft()
        order.append(v)
        for u in adj[v]:
            indegree[u] -= 1                # одной зависимостью меньше
            if indegree[u] == 0:            # долгов не осталось
                q.append(u)

    return order if len(order) == n else []  # не все -> был цикл


# =============================================================================
# can_finish — LeetCode 207, Course Schedule
#
# УСЛОВИЕ
#     Дано: num_courses курсов 0..num_courses-1 и список пар prerequisites.
#           Пара [a, b] означает: чтобы взять курс a, надо СНАЧАЛА пройти b.
#     Вернуть: True, если можно пройти все курсы; False, если есть цикл.
#
# ПРИМЕР
#     can_finish(2, [[1, 0]]) -> True
#         чтобы взять 1, нужен 0. Порядок 0, потом 1. Всё сходится.
#
#     can_finish(2, [[1, 0], [0, 1]]) -> False
#         1 требует 0, а 0 требует 1. Замкнутый круг.
#
# ГЛАВНОЕ ЗДЕСЬ — НАПРАВЛЕНИЕ, И ОНО ПЕРЕВЁРНУТОЕ
#     Пара записана как [что_беру, что_нужно_сначала].
#     Значит РАНЬШЕ идёт ВТОРОЙ элемент, и ребро смотрит b -> a.
#     В topo_order было наоборот: [a, b] давало ребро a -> b.
#
#     Это не придирка к формату — на интервью условие почти всегда
#     формулируют словами, и перевести слова в направление ребра
#     надо самому. Проговаривай вслух: "кто идёт первым?"
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Показывает, что детект цикла — это тот же Кан, просто вместо списка
#     возвращается сравнение счётчика с n.
#     Хранить весь order не нужно, хватит числа выполненных.
# =============================================================================

def can_finish(num_courses, prerequisites):
    adj = [[] for _ in range(num_courses)]
    indegree = [0] * num_courses

    for a, b in prerequisites:              # [a, b]: b раньше a
        adj[b].append(a)                    # ребро b -> a, ПЕРЕВЁРНУТО
        indegree[a] += 1

    q = deque(v for v in range(num_courses) if indegree[v] == 0)
    done = 0                                # список не нужен, хватит счётчика

    while q:
        v = q.popleft()
        done += 1
        for u in adj[v]:
            indegree[u] -= 1
            if indegree[u] == 0:
                q.append(u)

    return done == num_courses


# =============================================================================
# topo_order_dfs — та же задача, что topo_order, но через DFS
# НОСИТЕЛЬ: DFS с тремя цветами
#
# УСЛОВИЕ
#     Дано: n вершин 0..n-1 и список ориентированных рёбер.
#           Ребро [a, b] означает: a должен идти РАНЬШЕ b.
#     Вернуть: любой валидный топологический порядок.
#              Если есть цикл — пустой список.
#     Решить обходом в глубину, без indegree.
#
# ПРИМЕР
#     n = 4, edges = [[0,1], [0,2], [1,3], [2,3]]
#
#         0 -> 1
#         |    |
#         v    v
#         2 -> 3
#
#     dfs(0) -> dfs(1) -> dfs(3): у 3 детей нет, закрыли    order = [3]
#               у 1 дети кончились, закрыли                 order = [3, 1]
#            -> dfs(2): 3 уже чёрная, пропускаем, закрыли   order = [3, 1, 2]
#     закрыли 0                                             order = [3, 1, 2, 0]
#     разворот -> [0, 2, 1, 3]
#
# ИДЕЯ
#     Вершину записываем в order, когда ЗАКРЫЛИ: все, кто от неё зависит,
#     уже обойдены и записаны раньше. Значит в order она стоит ПОСЛЕ своих
#     потомков, а нужно наоборот — отсюда разворот в конце.
#
# ЗАЧЕМ ТРИ ЦВЕТА, А НЕ ОДИН seen
#     белая  — ещё не были
#     серая  — вошли, но не вышли: она сейчас на стеке рекурсии
#     чёрная — закрыта целиком
#
#     Цикл — это ребро в СЕРУЮ вершину: упёрлись в собственного предка.
#     Ребро в чёрную циклом не является: в ромбе к вершине 3 ведут два пути,
#     и вторым мы просто приходим в уже закрытую.
#     С одним seen эти два случая не различить: либо ромб объявляется циклом,
#     либо настоящий цикл проходит незамеченным.
#
# КОГДА БРАТЬ ЭТОТ ВАРИАНТ, А КОГДА КАНА
#     Кан короче и не упирается в лимит рекурсии — он основной.
#     DFS просят явно либо берут, когда обход в глубину уже написан
#     для другой части задачи.
# =============================================================================

def topo_order_dfs(n, edges):
    adj = [[] for _ in range(n)]
    for a, b in edges:                      # a раньше b, значит ребро a -> b
        adj[a].append(b)

    WHITE, GRAY, BLACK = 0, 1, 2            # не были / на стеке / закрыта
    color = [WHITE] * n
    order = []

    def dfs(v):                             # False — наткнулись на цикл
        color[v] = GRAY
        for u in adj[v]:
            if color[u] == GRAY:            # упёрлись в собственного предка
                return False
            if color[u] == WHITE and not dfs(u):
                return False
        color[v] = BLACK
        order.append(v)                     # ПОСЛЕ детей, при закрытии
        return True

    for v in range(n):                      # перебор стартов
        if color[v] == WHITE and not dfs(v):
            return []

    return order[::-1]                      # записывали с конца


# =============================================================================
# min_semesters — LeetCode 1136, Parallel Courses
# НОСИТЕЛЬ: Кан ПО СЛОЯМ
#
# УСЛОВИЕ
#     Дано: n курсов 0..n-1 и список ориентированных рёбер.
#           Ребро [a, b] означает: курс a надо пройти РАНЬШЕ b.
#           За один семестр можно взять сколько угодно курсов, но только те,
#           у которых все предшественники уже пройдены.
#     Вернуть: минимальное число семестров на все курсы.
#              Есть цикл — вернуть -1.
#
# ПРИМЕР
#     n = 4, edges = [[0,1], [0,2], [1,3], [2,3]]  -> 3
#
#         0 -> 1
#         |    |
#         v    v
#         2 -> 3
#
#     семестр 1: [0]       всё, что готово сразу
#     семестр 2: [1, 2]    оба ждали только 0
#     семестр 3: [3]       ждал и 1, и 2
#
# ЧТО ОТЛИЧАЕТСЯ ОТ topo_order
#     Одна строка: for _ in range(len(q)) вокруг тела цикла.
#     Слой очереди — это всё, что можно взять одновременно, то есть семестр.
#     Тот же приём, что считал минуты в oranges_rotting и шаги в shortest_hops.
#
# ПОЧЕМУ ОТВЕТ — ДЛИНА САМОЙ ДЛИННОЙ ЦЕПОЧКИ
#     Курс попадает в очередь, только когда обнулился ПОСЛЕДНИЙ его долг.
#     Значит его слой на единицу глубже самого позднего из предшественников.
#     Обычный BFS с seen поставил бы его на слой после ПЕРВОГО увиденного
#     предшественника — и занизил бы ответ.
#
# ПРО ЦИКЛ
#     Та же проверка, что всегда: прошли не все n курсов — остаток замкнут
#     в кольцо. Список не нужен, хватит счётчика done.
# =============================================================================

def min_semesters(n, edges):
    adj = [[] for _ in range(n)]
    indegree = [0] * n

    for a, b in edges:                      # a раньше b, значит ребро a -> b
        adj[a].append(b)
        indegree[b] += 1

    q = deque(v for v in range(n) if indegree[v] == 0)
    done = semesters = 0

    while q:
        for _ in range(len(q)):             # один слой = один семестр
            v = q.popleft()
            done += 1
            for u in adj[v]:
                indegree[u] -= 1
                if indegree[u] == 0:
                    q.append(u)
        semesters += 1

    return semesters if done == n else -1   # прошли не все -> был цикл


# =============================================================================
# ТЕСТЫ
# Порядков обычно несколько, поэтому проверяем ВАЛИДНОСТЬ, а не точный список.
# Помеченные (!) — ловушки.
# =============================================================================

def is_valid_order(n, edges, order):
    """Все n вершин ровно по разу И каждое ребро смотрит слева направо."""
    if sorted(order) != list(range(n)):
        return False
    pos = {v: i for i, v in enumerate(order)}
    return all(pos[a] < pos[b] for a, b in edges)


def test_topo_order():
    edges = [[0, 1], [0, 2], [1, 3], [2, 3]]
    assert is_valid_order(4, edges, topo_order(4, edges))
    # (!) цикл — обязан вернуться пустой список
    assert topo_order(2, [[0, 1], [1, 0]]) == []
    assert topo_order(3, [[0, 1], [1, 2], [2, 0]]) == []
    # (!) цикл не на всём графе, а только в куске
    assert topo_order(4, [[0, 1], [2, 3], [3, 2]]) == []
    # (!) рёбер нет — все вершины должны попасть в ответ
    assert sorted(topo_order(3, [])) == [0, 1, 2]
    # (!) изолированная вершина рядом с цепочкой
    res = topo_order(4, [[0, 1], [1, 2]])
    assert is_valid_order(4, [[0, 1], [1, 2]], res)
    # цепочка — порядок единственный
    assert topo_order(3, [[0, 1], [1, 2]]) == [0, 1, 2]
    # (!) обратная нумерация: ловит перепутанное направление ребра
    assert topo_order(3, [[2, 1], [1, 0]]) == [2, 1, 0]
    # ромб
    e = [[0, 1], [0, 2], [1, 3], [2, 3], [3, 4]]
    assert is_valid_order(5, e, topo_order(5, e))
    # (!) вырожденные
    assert topo_order(1, []) == [0]
    assert topo_order(0, []) == []
    # (!) петля из вершины в саму себя — тоже цикл
    assert topo_order(2, [[0, 0]]) == []


def test_can_finish():
    assert can_finish(2, [[1, 0]]) is True
    # (!) цикл из двух
    assert can_finish(2, [[1, 0], [0, 1]]) is False
    # зависимостей нет
    assert can_finish(3, []) is True
    # (!) длинная цепочка задом наперёд — ловит направление
    assert can_finish(4, [[1, 0], [2, 1], [3, 2]]) is True
    # (!) цикл из трёх
    assert can_finish(3, [[0, 1], [1, 2], [2, 0]]) is False
    # ромб без цикла
    assert can_finish(4, [[1, 0], [2, 0], [3, 1], [3, 2]]) is True
    # (!) цикл в стороне от основной цепочки
    assert can_finish(5, [[1, 0], [3, 4], [4, 3]]) is False
    # (!) вырожденные
    assert can_finish(1, []) is True
    assert can_finish(1, [[0, 0]]) is False      # курс требует сам себя


def test_topo_order_dfs():
    # (!) ромб: к вершине 3 ведут два пути, и это НЕ цикл
    edges = [[0, 1], [0, 2], [1, 3], [2, 3]]
    assert is_valid_order(4, edges, topo_order_dfs(4, edges))
    # (!) цикл — обязан вернуться пустой список
    assert topo_order_dfs(2, [[0, 1], [1, 0]]) == []
    assert topo_order_dfs(3, [[0, 1], [1, 2], [2, 0]]) == []
    # (!) цикл не на всём графе, а только в куске
    assert topo_order_dfs(4, [[0, 1], [2, 3], [3, 2]]) == []
    # (!) рёбер нет — все вершины должны попасть в ответ
    assert sorted(topo_order_dfs(3, [])) == [0, 1, 2]
    # (!) изолированная вершина рядом с цепочкой — ловит обход только от нуля
    res = topo_order_dfs(4, [[0, 1], [1, 2]])
    assert is_valid_order(4, [[0, 1], [1, 2]], res)
    # цепочка — порядок единственный, ловит забытый разворот
    assert topo_order_dfs(3, [[0, 1], [1, 2]]) == [0, 1, 2]
    # (!) обратная нумерация: ловит перепутанное направление ребра
    assert topo_order_dfs(3, [[2, 1], [1, 0]]) == [2, 1, 0]
    # ромб с хвостом
    e = [[0, 1], [0, 2], [1, 3], [2, 3], [3, 4]]
    assert is_valid_order(5, e, topo_order_dfs(5, e))
    # (!) вырожденные
    assert topo_order_dfs(1, []) == [0]
    assert topo_order_dfs(0, []) == []
    # (!) петля из вершины в саму себя — тоже цикл
    assert topo_order_dfs(2, [[0, 0]]) == []


def test_min_semesters():
    # базовый: два курса открывают третий
    assert min_semesters(3, [[0, 2], [1, 2]]) == 2
    # ромб
    assert min_semesters(4, [[0, 1], [0, 2], [1, 3], [2, 3]]) == 3
    # (!) зависимостей нет — всё берётся в один семестр
    assert min_semesters(3, []) == 1
    # цепочка — по курсу в семестр
    assert min_semesters(4, [[0, 1], [1, 2], [2, 3]]) == 4
    # (!) к курсу 3 ведут короткий и длинный путь — ждать надо длинного
    assert min_semesters(4, [[0, 3], [0, 1], [1, 2], [2, 3]]) == 4
    # (!) цикл
    assert min_semesters(3, [[0, 1], [1, 2], [2, 0]]) == -1
