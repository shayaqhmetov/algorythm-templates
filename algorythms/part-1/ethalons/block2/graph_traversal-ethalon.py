# ТЕСТЫ
# Помеченные (!) — ловушки. Кривая версия проходит простые тесты
# и падает именно на них.
# =============================================================================

def test_build_adj():
    assert build_adj(3, [[0, 1], [1, 2]]) == [[1], [0, 2], [1]]
    # (!) directed=True — только одна сторона
    assert build_adj(3, [[0, 1], [1, 2]], directed=True) == [[1], [2], []]
    # (!) вершины без рёбер обязаны присутствовать пустыми списками
    assert build_adj(3, []) == [[], [], []]
    assert build_adj(1, []) == [[]]


def test_count_components():
    assert count_components(5, [[0, 1], [1, 2], [3, 4]]) == 2
    # (!) изолированные вершины тоже компоненты, а их нет в edges
    assert count_components(5, [[0, 1]]) == 4
    assert count_components(4, []) == 4
    # весь граф связен
    assert count_components(4, [[0, 1], [1, 2], [2, 3]]) == 1
    # (!) цикл — обход не должен зациклиться
    assert count_components(3, [[0, 1], [1, 2], [2, 0]]) == 1
    # (!) обратное ребро: путь задан только как [1,0], а не [0,1]
    assert count_components(2, [[1, 0]]) == 1
    # (!) вырожденные
    assert count_components(1, []) == 1
    assert count_components(0, []) == 0
    # две компоненты по кольцу
    assert count_components(6, [[0, 1], [1, 2], [2, 0], [3, 4], [4, 5]]) == 2


def test_shortest_hops():
    edges = [[0, 1], [1, 2], [2, 5], [0, 3], [3, 4], [4, 5]]
    assert shortest_hops(6, edges, 0, 5) == 3
    assert shortest_hops(6, edges, 0, 1) == 1
    # (!) src == dst — ответ 0, ловит steps, стартующий с единицы
    assert shortest_hops(6, edges, 0, 0) == 0
    # (!) пути нет — вершина в другой компоненте
    assert shortest_hops(4, [[0, 1]], 0, 3) == -1
    assert shortest_hops(2, [], 0, 1) == -1
    # (!) BFS обязан выбрать короткий обход, а не длинный
    # 0-1-2-3-4 цепочка плюс прямое ребро 0-4
    assert shortest_hops(5, [[0, 1], [1, 2], [2, 3], [3, 4], [0, 4]], 0, 4) == 1
    # (!) обратное направление в неориентированном графе
    assert shortest_hops(3, [[0, 1], [1, 2]], 2, 0) == 2
    # (!) вырожденное
    assert shortest_hops(1, [], 0, 0) == 0


def test_dfs_order():
    edges = [[0, 1], [0, 2], [1, 3], [2, 4]]
    # (!) именно DFS, а не BFS: BFS дал бы [0, 1, 2, 3, 4]
    assert dfs_order(6, edges, 0) == [0, 1, 3, 2, 4]
    # (!) изолированная вершина 5 в результат не попадает
    assert 5 not in dfs_order(6, edges, 0)
    # старт не с нуля
    assert dfs_order(6, edges, 3) == [3, 1, 0, 2, 4]
    # (!) цикл — вершины не должны дублироваться
    assert dfs_order(3, [[0, 1], [1, 2], [2, 0]], 0) == [0, 1, 2]
    # цепочка
    assert dfs_order(4, [[0, 1], [1, 2], [2, 3]], 0) == [0, 1, 2, 3]
    # (!) вырожденные
    assert dfs_order(1, [], 0) == [0]
    assert dfs_order(3, [], 1) == [1]


test_build_adj()
test_count_components()
test_shortest_hops()
test_dfs_order()
print("ok — graph_traversal, все тесты прошли")
