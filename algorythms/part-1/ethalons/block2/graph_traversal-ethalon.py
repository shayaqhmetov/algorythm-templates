"""
ШАБЛОН 5 — BFS / DFS ПО ГРАФУ (adjacency list)

ОТЛИЧИЕ ОТ СЕТКИ
    В сетке соседи ВЫЧИСЛЯЮТСЯ: r+dr, c+dc — четыре направления, всегда одни.
    В графе соседи ХРАНЯТСЯ: их надо сначала построить в список смежности.
    Всё остальное — очередь, seen, popleft — идентично.
    Сетка это частный случай графа, где рёбра не записаны, а подразумеваются.

СПИСОК СМЕЖНОСТИ
    adj[v] — список вершин, куда можно попасть из v.
    Строится один раз в начале, за O(рёбер).

    НЕОРИЕНТИРОВАННЫЙ граф: каждое ребро пишем ДВАЖДЫ, в обе стороны.
    Забыть вторую строку — самая частая ошибка: половина графа
    становится недостижимой, а ошибка молчаливая.

    ОРИЕНТИРОВАННЫЙ: только одну сторону.

BFS ИЛИ DFS
    Кратчайший путь в невзвешенном графе / число шагов -> ТОЛЬКО BFS.
    Просто обойти, посчитать компоненты, найти цикл                -> любой.
    Рекурсивный DFS короче, но на 10^5 вершин упрётся в лимит рекурсии
    (в Python по умолчанию ~1000). Глубокий граф -> итеративный DFS или BFS.

ТРИ СКЕЛЕТА

    # список смежности (неориентированный)
    adj = [[] for _ in range(n)]
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)          # <- эту строку забывают

    # BFS
    q = deque([start])
    seen = {start}
    while q:
        v = q.popleft()
        for u in adj[v]:
            if u not in seen:
                seen.add(u)       # помечаем ПРИ ДОБАВЛЕНИИ
                q.append(u)

    # DFS рекурсивный
    def dfs(v):
        seen.add(v)               # помечаем ПРИ ВХОДЕ
        for u in adj[v]:
            if u not in seen:
                dfs(u)

    # DFS итеративный
    st = [start]
    while st:
        v = st.pop()              # pop с ХВОСТА — вот и вся разница с BFS
        if v in seen:
            continue              # помечаем ПРИ ИЗВЛЕЧЕНИИ, отсюда эта проверка
        seen.add(v)
        for u in reversed(adj[v]):
            if u not in seen:
                st.append(u)

BFS И ИТЕРАТИВНЫЙ DFS ОТЛИЧАЮТСЯ ОДНОЙ СТРОКОЙ
    popleft() — с головы -> BFS (волна).
    pop()     — с хвоста -> DFS (ныряем в глубину).
    Держи это в голове как одну конструкцию с переключателем, а не как две.

ПОЧЕМУ В ИТЕРАТИВНОМ DFS ПОМЕТКА ПРИ ИЗВЛЕЧЕНИИ
    В стеке одна вершина может лежать несколько раз: её положили разные соседи.
    Пометить при добавлении — порядок обхода перестанет совпадать
    с рекурсивным. Поэтому помечаем при снятии и в начале ставим
    проверку "уже были — пропускаем".
    reversed() нужен, чтобы порядок совпал с рекурсивным: стек переворачивает.

ЧЕТЫРЕ МЕСТА, ГДЕ ОШИБАЮТСЯ
    1. Забыть обратное ребро в неориентированном графе.
    2. Не проверять seen перед добавлением — на графе с циклом вечный цикл.
    3. Обойти только от вершины 0 и решить, что обошли всё.
       Граф может быть НЕСВЯЗНЫМ. Компоненты, изолированные вершины —
       нужен внешний цикл по всем стартам.
    4. Вершины без рёбер вообще не появятся в edges — если строить adj
       по рёбрам через словарь, они потеряются. Отсюда список на n элементов.

ПОРЯДОК ДРИЛЛА (5 минут)
    В сессию берёшь ОДНУ функцию.
    Ротация: 1) count_components  2) shortest_hops  3) dfs_order  4) с начала.

ПРИЗНАК, ЧТО ШАБЛОН СЕЛ
    Список смежности с обеими строками и цикл с seen пишутся не думая,
    а внимание уходит на то, что именно накапливать по дороге.
"""

from collections import deque


def build_adj(n, edges, directed=False):
    """
    Список смежности. Вынесен отдельно, потому что нужен всем трём функциям
    и на интервью пишется первой строкой почти всегда.
    directed=False — ребро идёт в обе стороны.
    """
    adj = [[] for _ in range(n)]            # список на n, а не словарь:
    for a, b in edges:                      # иначе вершины без рёбер потеряются
        adj[a].append(b)
        if not directed:
            adj[b].append(a)
    return adj


# =============================================================================
# count_components — LeetCode 323, Number of Connected Components
# НОСИТЕЛЬ: DFS рекурсивный + внешний цикл по стартам
#
# УСЛОВИЕ
#     Дано: n вершин с номерами 0..n-1 и список неориентированных рёбер.
#     Найти: число связных компонент.
#
# ПРИМЕР
#     n = 5, edges = [[0,1], [1,2], [3,4]]  -> 2
#
#         0 — 1 — 2      3 — 4
#         └── компонента 1 ──┘ └─ компонента 2 ─┘
#
#     n = 5, edges = [[0,1]]  -> 4
#         компонента {0,1}, плюс три одиночки: 2, 3, 4
#
# ИДЕЯ
#     Та же, что в num_islands: перебираем все вершины, наткнулись
#     на непосещённую — это новая компонента, увеличиваем счётчик
#     и обходим её целиком.
#     Внешний цикл — перебор СТАРТОВ, а не часть обхода.
#
# ПОЧЕМУ ОДИНОЧНЫЕ ВЕРШИНЫ ТОЖЕ КОМПОНЕНТЫ
#     Вершина 4 без единого ребра — полноценная компонента из одного элемента.
#     Она не встречается в edges, поэтому adj строим списком длины n,
#     а внешний цикл идёт по range(n), а не по вершинам из рёбер.
# =============================================================================

def count_components(n, edges):
    adj = build_adj(n, edges)
    seen = set()
    count = 0

    def dfs(v):
        seen.add(v)                         # помечаем ПРИ ВХОДЕ
        for u in adj[v]:
            if u not in seen:
                dfs(u)

    for v in range(n):                      # перебор стартов
        if v not in seen:
            count += 1
            dfs(v)

    return count


# =============================================================================
# shortest_hops — классика, вариация LeetCode 1971 / Word Ladder
# НОСИТЕЛЬ: BFS с подсчётом уровней
#
# УСЛОВИЕ
#     Дано: n вершин, неориентированные рёбра, вершины src и dst.
#     Найти: минимальное число РЁБЕР на пути из src в dst.
#            Если пути нет — вернуть -1.
#            src == dst -> 0.
#
# ПРИМЕР
#     n = 6, edges = [[0,1], [1,2], [2,5], [0,3], [3,4], [4,5]]
#
#         0 — 1 — 2
#         |       |
#         3 — 4 — 5
#
#     shortest_hops(6, edges, 0, 5) -> 3   (0-1-2-5, столько же 0-3-4-5)
#     shortest_hops(6, edges, 0, 0) -> 0
#
# ПОЧЕМУ ИМЕННО BFS
#     Нужен КРАТЧАЙШИЙ путь. BFS расходится волнами и доходит до вершины
#     на первом же слое, где она достижима.
#     DFS нашёл бы какой-то путь, но не обязательно короткий.
#
# СЧИТАЕМ РЁБРА, А НЕ ВЕРШИНЫ
#     Отсюда steps стартует с 0, а не с 1 (сравни с shortest_path в сетке,
#     где считались клетки и старт был 1). Всегда перечитывай, что просят.
#
# ПРОВЕРКА ЦЕЛИ ПРИ ИЗВЛЕЧЕНИИ
#     Вершина вышла из очереди — расстояние до неё уже финальное,
#     короче BFS не найдёт. Можно возвращать сразу.
#     Случай src == dst закрывается тем же кодом: цель проверяется
#     до первого шага, steps ещё 0.
# =============================================================================

def shortest_hops(n, edges, src, dst):
    adj = build_adj(n, edges)
    q = deque([src])
    seen = {src}
    steps = 0                               # считаем РЁБРА, старт = 0

    while q:
        for _ in range(len(q)):             # ровно один слой волны
            v = q.popleft()
            if v == dst:
                return steps
            for u in adj[v]:
                if u not in seen:
                    seen.add(u)             # помечаем ПРИ ДОБАВЛЕНИИ
                    q.append(u)
        steps += 1

    return -1


# =============================================================================
# dfs_order — базовая конструкция без обёртки в задачу
# НОСИТЕЛЬ: DFS итеративный, через стек
#
# УСЛОВИЕ
#     Дано: n вершин, неориентированные рёбра, стартовая вершина.
#     Вернуть: список вершин в порядке обхода в глубину (preorder),
#              БЕЗ рекурсии.
#     Порядок соседей — как в списке смежности.
#     Недостижимые вершины в результат не входят.
#
# ПРИМЕР
#     n = 6, edges = [[0,1], [0,2], [1,3], [2,4]], start = 0
#
#         0
#        / \
#       1   2
#       |   |
#       3   4        (вершина 5 изолирована)
#
#     -> [0, 1, 3, 2, 4]
#     Ныряем влево до упора (0-1-3), только потом идём в 2.
#     Для сравнения BFS дал бы [0, 1, 2, 3, 4] — по слоям.
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Рекурсивный DFS пишут все, итеративный — почти никто, и на глубоком
#     графе (10^5 вершин цепочкой) рекурсия падает по RecursionError.
#     Плюс он показывает главное: BFS и DFS отличаются одной строкой,
#     popleft против pop.
#
# ДВЕ ДЕТАЛИ, КОТОРЫЕ ЛЕГКО ПОТЕРЯТЬ
#     1. seen помечается ПРИ ИЗВЛЕЧЕНИИ, а не при добавлении.
#        В стеке одна вершина лежит по нескольку раз, её кладут разные соседи.
#        Отсюда 'if v in seen: continue' первой строкой в цикле.
#     2. reversed(adj[v]) — стек переворачивает порядок, а без reversed
#        обход пойдёт по соседям справа налево.
#        Не ошибка по сути, но с рекурсивной версией не совпадёт.
# =============================================================================

def dfs_order(n, edges, start):
    adj = build_adj(n, edges)
    seen = set()
    order = []
    st = [start]

    while st:
        v = st.pop()                        # с ХВОСТА — вот и вся разница с BFS
        if v in seen:                       # мог попасть в стек дважды
            continue
        seen.add(v)                         # помечаем ПРИ ИЗВЛЕЧЕНИИ
        order.append(v)
        for u in reversed(adj[v]):          # reversed, чтобы совпасть с рекурсией
            if u not in seen:
                st.append(u)

    return order


