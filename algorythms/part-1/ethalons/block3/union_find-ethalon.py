"""
ШАБЛОН 7 — UNION-FIND (DSU, система непересекающихся множеств)

КОГДА ПРИМЕНЯТЬ
    Неориентированный граф, рёбра ДОБАВЛЯЮТСЯ, и надо отвечать на вопросы
    "в одной ли группе эти двое", "сколько групп осталось",
    "какое ребро замкнуло цикл".
    Слова-маркеры: "объединить аккаунты", "друзья друзей", "провинции",
    "сколько групп", "лишнее ребро", "минимальное остовное дерево".

DSU ИЛИ ОБЫЧНЫЙ ОБХОД
    Граф дан целиком и вопрос один раз -> проще BFS/DFS (ШАБЛОН 5).
    Рёбра приходят по одному и ответ нужен после каждого -> DSU.
    DSU НЕ УМЕЕТ удалять рёбра — только добавлять. Есть удаления —
    это другая задача (обычно обработка запросов в обратном порядке).

ИДЕЯ В ОДНУ СТРОКУ
    Каждая группа — дерево. У дерева есть корень, и корень = имя группы.
    "В одной группе?" — это "один и тот же корень?".
    Объединить группы — подвесить один корень под другой.

СКЕЛЕТ (это и есть то, что заучивается)

    parent = list(range(n))       # сам себе корень
    size = [1] * n                # размер дерева, для балансировки
    count = n                     # сколько групп сейчас

    def find(x):                  # корень + сжатие пути
        while parent[x] != x:
            parent[x] = parent[parent[x]]      # перевешиваем через деда
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra == rb:
            return False                       # уже вместе — это цикл
        if size[ra] < size[rb]:
            ra, rb = rb, ra                    # меньшее дерево — под большее
        parent[rb] = ra
        size[ra] += size[rb]
        count -= 1
        return True

ДВЕ ОПТИМИЗАЦИИ, БЕЗ КОТОРЫХ ЭТО ПРОСТО СПИСОК
    1. Сжатие пути: по дороге к корню перевешиваем вершины повыше.
    2. Объединение по размеру: маленькое дерево подвешиваем к большому,
       иначе дерево вытянется в цепочку и find станет O(n).
    Вместе они дают практически O(1) на операцию.

ЧТО ВОЗВРАЩАЕТ union — И ПОЧЕМУ ЭТО ВАЖНО
    True  — слили две разные группы.
    False — оба конца ребра уже были в одной группе, значит ребро ЗАМКНУЛО
            ЦИКЛ. Это бесплатный детектор циклов в неориентированном графе,
            ради него DSU часто и берут.

ЧЕТЫРЕ МЕСТА, ГДЕ ОШИБАЮТСЯ
    1. parent[b] = a вместо parent[find(b)] = find(a).
       Связываются не корни, а случайные вершины — структура рассыпается.
    2. count уменьшается только когда union реально слил (вернул True).
       Иначе повторное ребро между теми же вершинами съест группу.
    3. Сравнивать надо КОРНИ: find(a) == find(b), а не a == b.
    4. Вершины пронумерованы с 1 — массив нужен длины n + 1,
       иначе IndexError на последней вершине.

ТРИ ВАРИАНТА, КОТОРЫЕ НАДО РАЗЛИЧАТЬ
    A) сама структура            — DSU                      (find + union)
    Б) сколько групп осталось    — count_components         (считаем слияния)
    В) какое ребро замкнуло цикл — find_redundant_connection (ловим False)

ПОРЯДОК ДРИЛЛА (5 минут)
    В сессию берёшь ОДНУ функцию. Читаешь блок над ней в -drill.py как
    задание, пишешь тело, гоняешь её тесты, сверяешь с этим файлом.
    Ротация: 1) DSU  2) count_components  3) find_redundant_connection
             4) с начала.
    DSU пишется каждый раз — на нём стоят обе остальные.

ПРИЗНАК, ЧТО ШАБЛОН СЕЛ
    find и union выходят подряд без пауз, а думаешь только про то,
    что означает False от union в этой конкретной задаче.
"""


# =============================================================================
# DSU — сама структура
# ВАРИАНТ A: find со сжатием пути + union по размеру
#
# УСЛОВИЕ
#     Дано: n элементов 0..n-1, изначально каждый сам по себе.
#     Сделать: DSU(n) с полями parent, size, count и методами
#              find(x)    -> корень группы x
#              union(a,b) -> True, если слили две РАЗНЫЕ группы;
#                            False, если они уже были одной.
#     count — сколько групп сейчас, обновляется само.
#
# ПРИМЕР
#     d = DSU(5)          группы: {0} {1} {2} {3} {4}, count = 5
#     d.union(0, 1)  True группы: {0,1} {2} {3} {4},   count = 4
#     d.union(2, 3)  True группы: {0,1} {2,3} {4},     count = 3
#     d.union(1, 0)  False — уже вместе, count не меняется
#     d.find(1) == d.find(0)  ->  True
#
# ПОЧЕМУ find ЧЕРЕЗ while, А НЕ ЧЕРЕЗ РЕКУРСИЮ
#     Рекурсивный find красивее, но на цепочке из 100 000 вершин
#     упирается в лимит рекурсии Python. Цикл не упирается.
#
# СТРОКА, КОТОРУЮ ЧАЩЕ ВСЕГО ПРОПУСКАЮТ
#     parent[x] = parent[parent[x]] — то самое сжатие пути.
#     Без неё код работает и тесты проходят, но на большом входе будет TLE.
# =============================================================================

class DSU:
    def __init__(self, n):
        self.parent = list(range(n))     # сам себе корень
        self.size = [1] * n
        self.count = n                   # групп столько же, сколько элементов

    def find(self, x):
        while self.parent[x] != x:
            self.parent[x] = self.parent[self.parent[x]]   # сжатие пути
            x = self.parent[x]
        return x

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)

        if ra == rb:
            return False                 # уже в одной группе

        if self.size[ra] < self.size[rb]:
            ra, rb = rb, ra              # меньшее дерево — под большее

        self.parent[rb] = ra
        self.size[ra] += self.size[rb]
        self.count -= 1
        return True


# =============================================================================
# count_components — LeetCode 323, Number of Connected Components
# ВАРИАНТ Б: считаем группы
#
# УСЛОВИЕ
#     Дано: n вершин 0..n-1 и список НЕОРИЕНТИРОВАННЫХ рёбер.
#     Вернуть: число связных компонент.
#
# ПРИМЕР
#     n = 5, edges = [[0,1], [1,2], [3,4]]
#
#         0 - 1 - 2      3 - 4
#
#     -> 2
#
#     старт: count = 5
#     [0,1] слили -> 4
#     [1,2] слили -> 3
#     [3,4] слили -> 2
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Это тот же count_components из ШАБЛОНА 5, но без построения adj
#     и без обхода: одна строка на ребро.
#     Полезно уметь обоими способами и вслух объяснить разницу:
#     обход — когда граф статичный, DSU — когда рёбра идут потоком.
#
# ЛОВУШКА С ИЗОЛИРОВАННЫМИ ВЕРШИНАМИ
#     Вершины без рёбер обязаны попасть в ответ. В DSU это бесплатно:
#     count стартует с n, а не с нуля.
# =============================================================================

def count_components(n, edges):
    dsu = DSU(n)

    for a, b in edges:
        dsu.union(a, b)                  # результат не нужен, count сам считает

    return dsu.count


# =============================================================================
# find_redundant_connection — LeetCode 684, Redundant Connection
# ВАРИАНТ В: ловим ребро, замкнувшее цикл
#
# УСЛОВИЕ
#     Дано: дерево из n вершин (пронумерованы С ЕДИНИЦЫ), в которое добавили
#           одно лишнее ребро. Рёбра даны в порядке добавления.
#     Вернуть: ребро, которое можно убрать, чтобы снова стало дерево.
#              Подходит ЛЮБОЕ ребро цикла, поэтому в условии уточняют:
#              вернуть то из них, которое стоит в списке ПОСЛЕДНИМ.
#
# ПРИМЕР
#     edges = [[1,2], [1,3], [2,3]]
#
#         1 - 2
#         |  /
#         3          -> [2,3]
#
#     [1,2] union True
#     [1,3] union True
#     [2,3] union False — 2 и 3 уже в одной группе, вот и цикл
#
#     edges = [[1,4], [3,4], [1,3], [1,2], [4,5]]  -> [1,3]
#     Цикл 1-4-3-1 собран из рёбер [1,4] [3,4] [1,3], последнее из них [1,3].
#     Ответ — не последнее ребро СПИСКА: после него идут ещё два.
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Весь алгоритм — это ОДНА проверка возвращаемого значения union.
#     Именно ради неё стоит помнить, что union что-то возвращает.
#
# ПОЧЕМУ ПЕРВОЕ СРАБОТАВШЕЕ union И ЕСТЬ "ПОСЛЕДНЕЕ" ИЗ УСЛОВИЯ
#     Слово "последнее" подбивает досмотреть список до конца. Не надо.
#     Первое ребро, на котором union вернул False, — это и есть последнее
#     ребро цикла: остальные рёбра цикла к этому моменту уже лежат в DSU,
#     то есть шли раньше. Шло бы какое-то из них позже — цикл замкнулся бы
#     не здесь, а на нём.
#     Идём слева направо и возвращаем первое сработавшее.
#
# ЛОВУШКА С НУМЕРАЦИЕЙ
#     Вершины 1..n, а массив parent индексируется с нуля.
#     Берём DSU(max_вершина + 1) и просто не трогаем нулевую ячейку.
#     Экономить тут нечего, а off-by-one на нумерации с единицы —
#     самая частая ошибка в задачах на DSU.
# =============================================================================

def find_redundant_connection(edges):
    if not edges:
        return []

    n = max(max(a, b) for a, b in edges)
    dsu = DSU(n + 1)                     # вершины с 1, нулевую ячейку не трогаем

    for a, b in edges:
        if not dsu.union(a, b):          # оба конца уже в одной группе
            return [a, b]

    return []


# =============================================================================
# ТЕСТЫ
# Помеченные (!) — ловушки. Кривая версия проходит простые тесты
# и падает именно на них.
# =============================================================================

def test_dsu():
    d = DSU(5)
    # старт: каждый сам себе корень
    assert d.find(3) == 3
    assert d.count == 5
    # базовое слияние
    assert d.union(0, 1) is True
    assert d.find(0) == d.find(1)
    assert d.count == 4
    # (!) повторное ребро: False и count НЕ меняется
    assert d.union(1, 0) is False
    assert d.count == 4
    # (!) слияние двух непустых деревьев, а не одиночек
    d.union(2, 3)
    assert d.union(0, 2) is True
    assert d.count == 2                  # {0,1,2,3} и {4}
    assert d.find(1) == d.find(3)
    assert d.find(4) != d.find(0)
    # (!) транзитивность через сжатый путь
    d.union(3, 4)
    assert d.count == 1
    assert len({d.find(i) for i in range(5)}) == 1
    # (!) вырожденный: одна вершина
    one = DSU(1)
    assert one.find(0) == 0
    assert one.count == 1
    # (!) длинная цепочка — сжатие пути не должно ломать корни
    chain = DSU(50)
    for i in range(49):
        assert chain.union(i, i + 1) is True
    assert chain.count == 1
    assert chain.find(0) == chain.find(49)


def test_count_components():
    # базовый
    assert count_components(5, [[0, 1], [1, 2], [3, 4]]) == 2
    # (!) изолированные вершины обязаны считаться
    assert count_components(5, []) == 5
    assert count_components(4, [[0, 1]]) == 3
    # всё связано
    assert count_components(4, [[0, 1], [1, 2], [2, 3]]) == 1
    # (!) дублирующее ребро не должно съедать компоненту
    assert count_components(3, [[0, 1], [1, 0], [0, 1]]) == 2
    # (!) цикл — компонента всё равно одна
    assert count_components(3, [[0, 1], [1, 2], [2, 0]]) == 1
    # (!) вырожденные
    assert count_components(0, []) == 0
    assert count_components(1, []) == 1
    # звезда
    assert count_components(5, [[0, 1], [0, 2], [0, 3], [0, 4]]) == 1


def test_find_redundant_connection():
    # базовый
    assert find_redundant_connection([[1, 2], [1, 3], [2, 3]]) == [2, 3]
    # (!) лишнее ребро в самом конце длинной цепочки
    assert find_redundant_connection([[1, 2], [2, 3], [3, 4], [1, 4]]) == [1, 4]
    # цикл замыкается рано, дальше просто дерево
    assert find_redundant_connection([[1, 2], [2, 1], [2, 3]]) == [2, 1]
    # (!) звезда плюс ребро между лучами
    assert find_redundant_connection([[1, 2], [1, 3], [1, 4], [3, 4]]) == [3, 4]
    # минимальный вход: петля из двух вершин
    assert find_redundant_connection([[1, 2], [1, 2]]) == [1, 2]
    # (!) лишнего ребра нет — честное дерево
    assert find_redundant_connection([[1, 2], [2, 3]]) == []
    assert find_redundant_connection([]) == []
    # (!) ответ — последнее ребро ЦИКЛА, а не последнее ребро списка
    assert find_redundant_connection(
        [[1, 4], [3, 4], [1, 3], [1, 2], [4, 5]]) == [1, 3]


test_dsu()
test_count_components()
test_find_redundant_connection()
print("ok — union_find, все тесты прошли")
