# next_greater_circular — LeetCode 503, Next Greater Element II
# ВАРИАНТ Г: массив замкнут в кольцо
#
# УСЛОВИЕ
#     Дано: массив чисел, замкнутый в кольцо — за последним элементом
#           снова идёт первый.
#     Вернуть: для каждого элемента ближайший СТРОГО больший, если идти
#              вправо по кругу. Такого нет — -1.
#
# ПРИМЕР
#     [1, 2, 1] -> [2, -1, 2]
#
#     Для последней единицы справа ничего нет, но по кругу за ней идёт
#     первая единица, а потом двойка. Двойка — максимум, ей ответа нет.
#
# ИДЕЯ — ПРОЙТИ МАССИВ ДВАЖДЫ
#     Кольцо разворачивается в ленту из двух копий: [1, 2, 1, 1, 2, 1].
#     Копию не строим — идём i от 0 до 2n - 1 и берём nums[i % n].
#     Первый круг — обычный next_greater. Второй круг закрывает тех,
#     кто остался в стеке: их ответ лежит левее, в начале массива.
#
# ПОЧЕМУ НА ВТОРОМ КРУГЕ НЕ КЛАДЁМ В СТЕК
#     Каждый индекс уже встал в очередь на первом круге. Второй круг нужен
#     только как источник "закрывающих" значений. Отсюда if i < n перед
#     append — единственное место в шаблоне, где append не безусловный.
#
# ПОЧЕМУ ХВАТАЕТ ДВУХ КРУГОВ
#     Ответ для элемента лежит не дальше чем в n - 1 шагах от него.
#     За два круга каждый элемент увидит всех остальных.
#     Кто и после этого остался в стеке — максимумы, у них -1.
# =============================================================================

def next_greater_circular(nums):
    n = len(nums)
    res = [-1] * n                       # максимумы так и останутся с -1
    stack = []                           # индексы, значения по убыванию

    for i in range(2 * n):               # два круга по кольцу
        x = nums[i % n]
        while stack and nums[stack[-1]] < x:
            res[stack.pop()] = x
        if i < n:                        # второй круг только закрывает
            stack.append(i)

    return res


# =============================================================================
# ТЕСТЫ
# Помеченные (!) — ловушки. Кривая версия проходит простые тесты
# и падает именно на них.
# =============================================================================

def test_next_greater():
    # базовый
    assert next_greater([2, 1, 2, 4, 3]) == [4, 2, 4, -1, -1]
    # (!) возрастающий — каждый закрывается соседом
    assert next_greater([1, 2, 3]) == [2, 3, -1]
    # (!) убывающий — не закрывается никто, весь хвост из -1
    assert next_greater([3, 2, 1]) == [-1, -1, -1]
    # (!) равные элементы: нужен СТРОГО больший
    assert next_greater([2, 2, 3]) == [3, 3, -1]
    assert next_greater([2, 2]) == [-1, -1]
    # (!) один элемент выталкивает сразу несколько
    assert next_greater([5, 4, 3, 9]) == [9, 9, 9, -1]
    # (!) вырожденные
    assert next_greater([]) == []
    assert next_greater([1]) == [-1]
    # отрицательные
    assert next_greater([-2, -1, -3]) == [-1, -1, -1]


def test_daily_temperatures():
    # базовый
    assert daily_temperatures([73, 74, 75, 71, 69, 72, 76, 73]) == [1, 1, 4, 2, 1, 1, 0, 0]
    # монотонный рост
    assert daily_temperatures([30, 40, 50, 60]) == [1, 1, 1, 0]
    assert daily_temperatures([30, 60, 90]) == [1, 1, 0]
    # (!) равные температуры — потеплением не считаются
    assert daily_temperatures([30, 30, 30]) == [0, 0, 0]
    # (!) убывающие — весь ответ нулевой
    assert daily_temperatures([90, 80, 70]) == [0, 0, 0]
    # (!) ждать долго — проверяет, что расстояние, а не единица
    assert daily_temperatures([50, 40, 30, 20, 60]) == [4, 3, 2, 1, 0]
    # (!) вырожденные
    assert daily_temperatures([]) == []
    assert daily_temperatures([50]) == [0]


def test_largest_rectangle():
    # базовый
    assert largest_rectangle([2, 1, 5, 6, 2, 3]) == 10
    # (!) выгоднее взять один высокий, чем два по нижнему
    assert largest_rectangle([2, 4]) == 4
    # (!) низкий столбик посередине не должен мешать краям
    assert largest_rectangle([2, 1, 2]) == 3
    # монотонные — ответ в середине, а не на краю
    assert largest_rectangle([5, 4, 3, 2, 1]) == 9
    assert largest_rectangle([1, 2, 3, 4, 5]) == 9
    # (!) все равны — ширина на всю гистограмму
    assert largest_rectangle([3, 3, 3]) == 9
    # (!) самый низкий тянется через весь массив
    assert largest_rectangle([6, 7, 5, 2, 4, 5, 9, 3]) == 16
    # (!) ноль разрезает гистограмму пополам
    assert largest_rectangle([1, 0, 1]) == 1
    # (!) вырожденные
    assert largest_rectangle([]) == 0
    assert largest_rectangle([1]) == 1
    assert largest_rectangle([0]) == 0


def test_next_greater_circular():
    # базовый
    assert next_greater_circular([1, 2, 1]) == [2, -1, 2]
    assert next_greater_circular([1, 2, 3, 4, 3]) == [2, 3, 4, -1, 4]
    # (!) убывающий: без кольца были бы одни -1
    assert next_greater_circular([3, 2, 1]) == [-1, 3, 3]
    # возрастающий — от обычного next_greater не отличается
    assert next_greater_circular([1, 2, 3]) == [2, 3, -1]
    # (!) все равны — строго большего нет ни у кого
    assert next_greater_circular([2, 2, 2]) == [-1, -1, -1]
    # (!) максимум встречается дважды — оба без ответа
    assert next_greater_circular([5, 1, 5]) == [-1, 5, -1]
    # (!) ответ для последнего — далеко в начале, а не первый элемент
    assert next_greater_circular([1, 1, 9, 4, 2]) == [9, 9, -1, 9, 9]
    # (!) вырожденные
    assert next_greater_circular([]) == []
    assert next_greater_circular([7]) == [-1]
    # длинный спуск: всем, кроме первого, отвечает первый
    assert next_greater_circular([5, 4, 3, 2, 1]) == [-1, 5, 5, 5, 5]


