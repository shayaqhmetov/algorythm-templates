# =============================================================================
# next_greater — LeetCode 496 (упрощённая версия)
# ВАРИАНТ A: ответ — значение соседа
#
# УСЛОВИЕ
#     Дано: массив чисел.
#     Вернуть: массив той же длины, где на месте i стоит первое число
#              СПРАВА от i, которое строго больше nums[i].
#              Такого нет — -1.
#
# ПРИМЕР
#     nums = [2, 1, 2, 4, 3]  ->  [4, 2, 4, -1, -1]
#
#     i=0  x=2  стек пуст -> кладём 0            стек: [0]
#     i=1  x=1  1 < 2, никого не выталкивает     стек: [0,1]
#     i=2  x=2  выталкивает 1 (res[1]=2)         стек: [0,2]
#               двойку с индексом 0 НЕ выталкивает: нужен строго больший
#     i=3  x=4  выталкивает 2 (res[2]=4)
#               выталкивает 0 (res[0]=4)         стек: [3]
#     i=4  x=3  3 < 4                            стек: [3,4]
#
#     в стеке остались 3 и 4 — им ответа нет, у них так и лежит -1
#
# ПОЧЕМУ ЭТО РАБОТАЕТ
#     Пока элемент лежит в стеке, справа от него не встретилось ничего
#     большего. Как только встретилось — это по построению ПЕРВОЕ такое,
#     потому что мы идём слева направо и не пропускаем ничего.
#
# ЗАЧЕМ res ЗАПОЛНЕН МИНУС ЕДИНИЦАМИ ЗАРАНЕЕ
#     Это и есть обработка хвоста. Кто не был вытолкнут — тот так и
#     остался с -1, отдельного цикла по остаткам стека не нужно.
# =============================================================================

def next_greater(nums):
    res = [-1] * len(nums)               # хвост обработан заранее
    stack = []                           # индексы, значения по убыванию

    for i, x in enumerate(nums):
        while stack and nums[stack[-1]] < x:      # x закрывает верхних
            res[stack.pop()] = x
        stack.append(i)                  # всегда, без условий

    return res


# =============================================================================
# daily_temperatures — LeetCode 739, Daily Temperatures
# ВАРИАНТ Б: ответ — расстояние
#
# УСЛОВИЕ
#     Дано: температуры по дням.
#     Вернуть: для каждого дня, сколько дней ждать до первого более тёплого.
#              Такого дня нет — 0.
#
# ПРИМЕР
#     temps = [73, 74, 75, 71, 69, 72, 76, 73]
#     ->      [ 1,  1,  4,  2,  1,  1,  0,  0]
#
#     75 (индекс 2) ждёт до 76 (индекс 6): 6 - 2 = 4 дня.
#
# ЧТО ОТЛИЧАЕТСЯ ОТ ВАРИАНТА A
#     Ровно одна строка: вместо значения записываем i - j.
#     Вот ради этого в стеке и лежат индексы: значение соседа тут не нужно
#     вообще, нужна дистанция.
#
# ХВОСТ
#     Заполняем нулями заранее — дни, для которых потепления не случилось,
#     так и останутся с нулём.
# =============================================================================

def daily_temperatures(temps):
    res = [0] * len(temps)
    stack = []                           # индексы дней, ждущих потепления

    for i, t in enumerate(temps):
        while stack and temps[stack[-1]] < t:
            j = stack.pop()
            res[j] = i - j               # расстояние, а не значение
        stack.append(i)

    return res


# =============================================================================
# largest_rectangle — LeetCode 84, Largest Rectangle in Histogram
# ВАРИАНТ В: ответ — ширина между двумя границами
#
# УСЛОВИЕ
#     Дано: гистограмма — массив высот столбиков ширины 1.
#     Вернуть: площадь самого большого прямоугольника, который в неё влезает.
#
# ПРИМЕР
#     heights = [2, 1, 5, 6, 2, 3]  ->  10
#
#         _
#       _| |
#      |5|6|         столбики 5 и 6 дают прямоугольник 5 x 2 = 10
#     _| | |_ _
#    |2|1| |2|3|
#
# ИДЕЯ
#     Переберём, какой столбик является САМЫМ НИЗКИМ в прямоугольнике.
#     Тогда высота фиксирована, и надо только максимально растянуться
#     влево и вправо, пока соседи не ниже.
#     Левая граница — первый СЛЕВА, кто ниже. Правая — первый СПРАВА, кто ниже.
#     То есть две задачи "следующий меньший", и обе решает один проход.
#
# ЧТО ЗДЕСЬ ПРОИСХОДИТ ПРИ pop
#     Столбик выталкивается пришедшим более низким h.
#     Значит справа от него граница — это i.
#     А слева граница — тот, кто лежит в стеке ПОД ним: стек возрастающий,
#     поэтому под ним лежит ближайший, кто ниже.
#     Ширина = i - stack[-1] - 1, а если стек опустел, столбик тянется
#     до самого начала: ширина = i.
#
# ЗАЧЕМ ЗАМЫКАЮЩИЙ НОЛЬ
#     После цикла в стеке остаются столбики, которых никто не вытолкнул.
#     Вместо отдельной обработки хвоста дописываем в конец нулевую высоту:
#     она ниже всех и вытолкнет весь стек тем же самым кодом.
#     Приём общий: искусственный элемент вместо ветвления.
#
# ЗНАК СРАВНЕНИЯ ЗДЕСЬ ДРУГОЙ
#     Выталкиваем, пока верхний БОЛЬШЕ ИЛИ РАВЕН пришедшему — ищем меньший,
#     а не больший. Стек возрастающий, а не убывающий.
#     На равных высотах >= даёт лишний pop, но ответ не портит:
#     более широкий прямоугольник посчитается на последнем из равных.
# =============================================================================

def largest_rectangle(heights):
    hs = heights + [0]                   # замыкающий ноль вытолкнет стек
    stack = []                           # индексы, высоты по возрастанию
    best = 0

    for i, h in enumerate(hs):
        while stack and hs[stack[-1]] >= h:
            height = hs[stack.pop()]
            left = stack[-1] + 1 if stack else 0   # стек пуст — тянемся до начала
            best = max(best, height * (i - left))
        stack.append(i)

    return best


