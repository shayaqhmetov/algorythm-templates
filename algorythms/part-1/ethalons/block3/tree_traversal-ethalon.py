from collections import deque


class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right


def build(values):
    """
    Собирает дерево из списка в формате LeetCode: значения по уровням,
    None вместо отсутствующего узла. Нужна только для тестов.
    [3, 9, 20, None, None, 15, 7] ->

            3
           / \
          9  20
             / \
            15  7
    """
    if not values or values[0] is None:
        return None

    root = TreeNode(values[0])
    q = deque([root])
    i = 1

    while q and i < len(values):
        node = q.popleft()

        if i < len(values) and values[i] is not None:
            node.left = TreeNode(values[i])
            q.append(node.left)
        i += 1

        if i < len(values) and values[i] is not None:
            node.right = TreeNode(values[i])
            q.append(node.right)
        i += 1

    return root


# =============================================================================
# max_depth — LeetCode 104, Maximum Depth of Binary Tree
# ВАРИАНТ A: DFS снизу вверх, ответ собирается из детей
#
# УСЛОВИЕ
#     Вернуть число узлов на самом длинном пути от корня до листа.
#     Пустое дерево — 0.
#
# ПРИМЕР
#             3          глубина 1
#            / \
#           9  20        глубина 2
#              / \
#             15  7      глубина 3      -> 3
#
# ИДЕЯ
#     Глубина дерева = 1 + глубина самого глубокого поддерева.
#     Это буквально одна строка, и она же — весь скелет рекурсии:
#     спросили у детей, добавили себя.
#
# ЧТО ЗДЕСЬ НЕЙТРАЛЬНОЕ ЗНАЧЕНИЕ
#     Для пустого узла возвращаем 0. Тогда лист даёт 1 + max(0, 0) = 1
#     автоматически, и отдельной проверки "это лист" не нужно.
#     Лишняя проверка на лист — самая частая ненужная строка в этой задаче.
# =============================================================================

def max_depth(root):
    if root is None:                     # база — первой строкой
        return 0

    return 1 + max(max_depth(root.left), max_depth(root.right))


# =============================================================================
# level_order — LeetCode 102, Binary Tree Level Order Traversal
# ВАРИАНТ Б: BFS по уровням
#
# УСЛОВИЕ
#     Вернуть список уровней: [[корень], [второй уровень], ...].
#     Пустое дерево — пустой список.
#
# ПРИМЕР
#             3
#            / \
#           9  20
#              / \
#             15  7      -> [[3], [9, 20], [15, 7]]
#
# ПОЧЕМУ ЭТО ТОТ ЖЕ BFS, ЧТО И В СЕТКЕ
#     deque, popleft, len(q) ДО цикла — ровно как в ШАБЛОНЕ 4.
#     Соседи берутся не из DIRS, а из node.left / node.right,
#     и seen не нужен: в дерево нельзя вернуться.
#
# ЕДИНСТВЕННАЯ ТОНКОСТЬ
#     len(q) вычисляется ДО for: внутри цикла мы дописываем детей в ту же
#     очередь, и если брать len на ходу, уровни слипнутся в один.
# =============================================================================

def level_order(root):
    if root is None:
        return []

    res = []
    q = deque([root])

    while q:
        level = []
        for _ in range(len(q)):          # ровно один уровень
            node = q.popleft()
            level.append(node.val)
            if node.left:                # проверяем ДО append
                q.append(node.left)
            if node.right:
                q.append(node.right)
        res.append(level)

    return res


# =============================================================================
# inorder — LeetCode 94, Binary Tree Inorder Traversal
# ВАРИАНТ В: тот же обход, но стеком вместо рекурсии
#
# УСЛОВИЕ
#     Вернуть значения в порядке "левое поддерево, узел, правое поддерево".
#
# ПРИМЕР
#             1
#              \
#               2
#              /
#             3          -> [1, 3, 2]
#
#     Для BST inorder всегда даёт отсортированный список — это и есть
#     самый быстрый способ проверить BST на интервью.
#
# ЗАЧЕМ ПИСАТЬ ЕГО БЕЗ РЕКУРСИИ
#     Рекурсивный вариант — три строки, его спрашивают как разминку,
#     а потом просят "теперь без рекурсии". Итеративный inorder —
#     стандартный доп. вопрос, и он же основа для "k-й по величине в BST".
#
# КАК ЭТО РАБОТАЕТ
#     Спускаемся влево до упора, складывая узлы в стек — это отложенные
#     дела. Стек кончился слева — снимаем верхний, записываем его
#     (левое поддерево уже пройдено) и переходим направо.
#     cur is not None or stack — цикл жив, пока есть куда идти
#     ИЛИ есть отложенные дела. Забыть половину условия — обход обрывается.
# =============================================================================

def inorder(root):
    res = []
    stack = []
    cur = root

    while cur is not None or stack:
        while cur is not None:           # влево до упора
            stack.append(cur)
            cur = cur.left

        cur = stack.pop()                # левое поддерево пройдено
        res.append(cur.val)
        cur = cur.right                  # теперь направо

    return res


