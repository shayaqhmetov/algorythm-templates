# is_valid_bst — LeetCode 98, Validate Binary Search Tree
# ВАРИАНТ Г: DFS сверху вниз, тащим границы
#
# УСЛОВИЕ
#     Проверить, что дерево — корректное BST: в левом поддереве узла ВСЕ
#     значения строго меньше, в правом — строго больше.
#
# ПРИМЕР
#             5
#            / \
#           1   4          -> False
#              / \
#             3   6
#
#     4 больше 1 и меньше 6 — с отцом всё в порядке.
#     Но 3 и 4 лежат в ПРАВОМ поддереве пятёрки, а 3 < 5 и 4 < 5.
#
# ГЛАВНАЯ ОШИБКА ЭТОЙ ЗАДАЧИ
#     Сравнить узел только с родителем. Такая версия проходит примеры
#     из условия и разваливается ровно на дереве выше.
#     Правило BST — про ВСЁ поддерево, а не про соседний узел.
#
# ИДЕЯ
#     Каждому узлу спускаем коридор (low, high), в который он обязан попасть.
#     Пошли влево — верхняя граница становится значением узла.
#     Пошли вправо — нижняя. Границы только сужаются.
#     Корень стартует с (-inf, +inf): ему можно всё.
#
# ПОЧЕМУ СТРОГИЕ НЕРАВЕНСТВА
#     Дубликаты в BST запрещены условием задачи, поэтому <= и >= сразу
#     False. Это отдельный тест ниже.
# =============================================================================

def is_valid_bst(root):
    def go(node, low, high):
        if node is None:                 # пустое поддерево валидно
            return True

        if not (low < node.val < high):  # вышли из коридора
            return False

        return (go(node.left, low, node.val) and
                go(node.right, node.val, high))

    return go(root, float('-inf'), float('inf'))


