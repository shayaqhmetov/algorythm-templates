from functools import cmp_to_key


# =============================================================================
# counting_sort — сортировка подсчётом
# ВАРИАНТ A: без единого сравнения
#
# УСЛОВИЕ
#     Дано: список НЕОТРИЦАТЕЛЬНЫХ целых.
#     Вернуть: новый отсортированный список.
#     Время O(n + k), где k — максимальное значение.
#
# ПРИМЕР
#     [3, 1, 0, 3, 1]
#
#     счётчики:  0 -> 1,  1 -> 2,  2 -> 0,  3 -> 2
#     развернули: [0, 1, 1, 3, 3]
#
# КОГДА ЭТО ВЫГОДНО
#     Оценки 0..100, возрасты, буквы алфавита, байты — всё, где значений
#     заведомо мало. На миллионе чисел до 100 это быстрее любого sorted().
#     На миллионе чисел до миллиарда — катастрофа по памяти.
#
# ЛОВУШКА С РАЗМЕРОМ
#     Ячеек нужно max + 1: под индекс max тоже нужна ячейка.
#     И проверка на пустой вход до max(), иначе ValueError.
# =============================================================================

def counting_sort(nums):
    if not nums:
        return []

    count = [0] * (max(nums) + 1)        # +1 — под сам максимум
    for x in nums:
        count[x] += 1

    res = []
    for value, times in enumerate(count):
        res.extend([value] * times)      # times может быть нулём
    return res


# =============================================================================
# sort_by_freq — LeetCode 451, Sort Characters By Frequency
# ВАРИАНТ Б: составной ключ
#
# УСЛОВИЕ
#     Дано: строка.
#     Вернуть: ту же строку, где символы сгруппированы и идут по УБЫВАНИЮ
#              частоты. Частоты равны — по ВОЗРАСТАНИЮ символа.
#
# ПРИМЕР
#     "tree"  ->  "eert"
#     e встречается дважды, r и t по разу, между ними порядок по алфавиту
#
#     "cccaaa" -> "aaaccc"     частоты равны, решает алфавит
#
# КЛЮЧ ИЗ ДВУХ ПОЛЕЙ
#     key=lambda ch: (-freq[ch], ch)
#     Первое поле с минусом — значит по убыванию. Второе без минуса —
#     по возрастанию. Кортежи сравниваются слева направо, поэтому второе
#     поле решает только при равном первом. Это и есть tie-break.
#
# ПОЧЕМУ МИНУС РАБОТАЕТ ТОЛЬКО НА ЧИСЛАХ
#     -freq[ch] — обычное число. Для символа минус не написать,
#     поэтому "по убыванию частоты, по возрастанию символа" одним ключом
#     выражается, а "по убыванию символа" — уже нет.
# =============================================================================

def sort_by_freq(s):
    freq = {}
    for ch in s:
        freq[ch] = freq.get(ch, 0) + 1

    order = sorted(freq, key=lambda ch: (-freq[ch], ch))
    return "".join(ch * freq[ch] for ch in order)


# =============================================================================
# largest_number — LeetCode 179, Largest Number
# ВАРИАНТ В: правило на паре, cmp_to_key
#
# УСЛОВИЕ
#     Дано: список неотрицательных чисел.
#     Вернуть: наибольшее число, которое можно составить, склеив их
#              в каком-то порядке. Ответ — строка.
#
# ПРИМЕР
#     [10, 2]          ->  "210"        ("210" > "102")
#     [3, 30, 34, 5, 9] -> "9534330"
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Ключа здесь не существует. Из одного числа не вытащить величину,
#     по которой его можно расставить: 3 идёт перед 30, но после 34.
#     Порядок определяется только ПАРОЙ — вот ради этого случая и нужен
#     cmp_to_key, а на интервью это стандартный вопрос "а если ключа нет".
#
# ПРАВИЛО ОДНОЙ СТРОКОЙ
#     a должно идти раньше b, если склейка a + b больше, чем b + a.
#     Сравниваем строки, а не числа: "3" + "30" = "330" против "303".
#     Это сравнение транзитивно, поэтому сортировка корректна.
#
# ЛОВУШКА С НУЛЯМИ
#     [0, 0] даст "00", а правильный ответ — "0".
#     Достаточно посмотреть на первый символ результата: если это ноль,
#     значит все числа нули.
# =============================================================================

def largest_number(nums):
    if not nums:
        return ""

    parts = [str(x) for x in nums]
    # отрицательное — значит a левее b
    parts.sort(key=cmp_to_key(lambda a, b: -1 if a + b > b + a else 1))

    if parts[0] == "0":                  # одни нули
        return "0"
    return "".join(parts)


# =============================================================================
# merge_intervals — LeetCode 56, Merge Intervals
# ВАРИАНТ Г: сортировка — не ответ, а подготовка к одному проходу
#
# УСЛОВИЕ
#     Дано: список отрезков [начало, конец], в произвольном порядке.
#     Вернуть: список, в котором все пересекающиеся отрезки слиты.
#              Касание концами ([1,4] и [4,5]) — тоже пересечение.
#              Ответ упорядочен по началу. Вход не менять.
#
# ПРИМЕР
#     [[1,3], [2,6], [8,10], [15,18]]  ->  [[1,6], [8,10], [15,18]]
#
#         1──3
#           2────6            ->  1─────6
#                   8──10             8──10
#                         15──18            15──18
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     В первых трёх сортировка и была ответом. Здесь она только
#     ПОДГОТОВКА: после неё задача решается одним проходом.
#     На интервью так бывает чаще всего, и узнать это надо по условию:
#     "отрезки", "встречи", "расписание" — почти всегда сначала sort по началу.
#
# ПОЧЕМУ ПОСЛЕ СОРТИРОВКИ ХВАТАЕТ ОДНОГО ПРОХОДА
#     Отрезки идут по возрастанию начала. Значит новый отрезок может
#     пересечься только с ПОСЛЕДНИМ из уже собранных: все более ранние
#     кончились ещё раньше. Сравниваем с res[-1] и больше ни с кем.
#
# ДВЕ ЛОВУШКИ
#     1. max при слиянии. Новый отрезок может лежать ЦЕЛИКОМ ВНУТРИ
#        последнего: [1,10] и [2,3]. Просто записать его конец — значит
#        укоротить отрезок до [1,3].
#     2. <=, а не <. Касание [1,4] и [4,5] по условию сливается.
# =============================================================================

def merge_intervals(intervals):
    res = []

    for start, end in sorted(intervals, key=lambda x: x[0]):   # по началу
        if res and start <= res[-1][1]:          # задел последний собранный
            res[-1][1] = max(res[-1][1], end)    # max: новый может быть внутри
        else:
            res.append([start, end])             # новый список — вход цел

    return res


