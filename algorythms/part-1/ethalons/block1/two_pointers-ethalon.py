# remove_duplicates — LeetCode 26, Remove Duplicates from Sorted Array
# ФОРМА Б: то же самое, но условие записи сложнее
#
# УСЛОВИЕ
#     Дано: ОТСОРТИРОВАННЫЙ массив.
#     Сделать: убрать дубликаты на месте, вернуть длину уникальной части.
#              Что лежит за этой длиной — неважно.
#
# ПРИМЕР
#     nums = [1, 1, 2, 2, 3]  ->  вернуть 3, массив начинается с [1, 2, 3, ...]
#
#     slow=1 (первый элемент уникален по определению, его не трогаем)
#     fast=1: nums[1]=1 == nums[slow-1]=1  — дубликат, пропускаем
#     fast=2: nums[2]=2 != nums[0]=1       — новый, пишем в slow=1, slow -> 2
#     fast=3: nums[3]=2 == nums[1]=2       — дубликат, пропускаем
#     fast=4: nums[4]=3 != nums[1]=2       — новый, пишем в slow=2, slow -> 3
#
#     вернули 3
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Тот же каркас формы Б, но сравниваем не с константой (как с нулём),
#     а с ПРЕДЫДУЩИМ ЗАПИСАННЫМ. Отсюда nums[slow - 1] — последнее,
#     что мы положили.
#
#     Работает только на отсортированном массиве: дубликаты идут подряд,
#     поэтому достаточно сравнить с одним предыдущим, а не искать по всему.
#     Множество для этого не нужно — оно бы съело O(n) памяти зря.
#
# Замечание: slow стартует с 1, а не с 0. Первый элемент уникален всегда,
# он уже на своём месте. Отсюда же range(1, ...) в цикле.
# =============================================================================

def remove_duplicates(nums):
    if not nums:
        return 0

    slow = 1

    for fast in range(1, len(nums)):
        if nums[fast] != nums[slow - 1]:   # отличается от последнего записанного
            nums[slow] = nums[fast]
            slow += 1

    return slow


