def test_two_sum_sorted():
    # базовый
    assert two_sum_sorted([2, 7, 11, 15], 9) == [0, 1]
    # (!) пары нет — указатели должны сойтись и вернуть []
    assert two_sum_sorted([2, 7, 11, 15], 100) == []
    assert two_sum_sorted([2, 7, 11, 15], 3) == []      # меньше любой пары
    # ответ на краях
    assert two_sum_sorted([1, 2, 3, 4], 5) == [0, 3]
    # ответ в середине
    assert two_sum_sorted([1, 2, 3, 4, 4, 9, 56, 90], 8) == [3, 4]
    # (!) дубликаты — соседние равные элементы
    assert two_sum_sorted([0, 0, 3, 4], 0) == [0, 1]
    # (!) отрицательные числа
    assert two_sum_sorted([-3, -1, 0, 2, 5], -4) == [0, 1]
    assert two_sum_sorted([-3, -1, 0, 2, 5], 2) == [0, 4]
    # (!) вырожденные — один элемент нельзя взять дважды
    assert two_sum_sorted([5], 10) == []                 # left < right сразу False
    assert two_sum_sorted([], 0) == []
    assert two_sum_sorted([1, 2], 3) == [0, 1]           # минимальный рабочий вход


def test_is_palindrome():
    # базовые
    assert is_palindrome("abcba") is True                # нечётная длина
    assert is_palindrome("abba") is True                 # чётная длина
    assert is_palindrome("racecar") is True
    # не палиндромы
    assert is_palindrome("abca") is False
    assert is_palindrome("ab") is False
    # (!) вырожденные
    assert is_palindrome("") is True                     # цикл не выполнится
    assert is_palindrome("a") is True                    # средний символ не сравниваем
    assert is_palindrome("aa") is True
    # (!) отличие в самой середине — ловит преждевременный выход из цикла
    assert is_palindrome("abcda") is False
    assert is_palindrome("aabaa") is True


def test_move_zeroes():
    # базовый
    assert move_zeroes([0, 1, 0, 3, 12]) == [1, 3, 12, 0, 0]
    # (!) только нули — slow остался 0, весь массив дозаполняется
    assert move_zeroes([0, 0]) == [0, 0]
    # (!) нулей нет — массив не должен измениться
    assert move_zeroes([1, 2, 3]) == [1, 2, 3]
    # (!) порядок ненулевых обязан сохраниться (не swap, а сдвиг!)
    assert move_zeroes([0, 3, 0, 1, 2]) == [3, 1, 2, 0, 0]
    # ноль в начале / в конце
    assert move_zeroes([0, 1]) == [1, 0]
    assert move_zeroes([1, 0]) == [1, 0]
    assert move_zeroes([0, 0, 1]) == [1, 0, 0]
    # (!) вырожденные
    assert move_zeroes([]) == []
    assert move_zeroes([0]) == [0]
    assert move_zeroes([1]) == [1]


def test_remove_duplicates():
    # базовый: проверяем И длину, И содержимое префикса
    a = [1, 1, 2, 2, 3]
    assert remove_duplicates(a) == 3
    assert a[:3] == [1, 2, 3]
    # (!) все элементы одинаковые
    a = [1, 1, 1]
    assert remove_duplicates(a) == 1
    assert a[:1] == [1]
    # (!) дубликатов нет — ничего не должно сдвинуться
    a = [1, 2, 3]
    assert remove_duplicates(a) == 3
    assert a[:3] == [1, 2, 3]
    # длинный вход
    a = [0, 0, 1, 1, 1, 2, 2, 3, 3, 4]
    assert remove_duplicates(a) == 5
    assert a[:5] == [0, 1, 2, 3, 4]
    # (!) дубликаты только в хвосте
    a = [1, 2, 3, 3]
    assert remove_duplicates(a) == 3
    assert a[:3] == [1, 2, 3]
    # (!) отрицательные
    a = [-3, -3, -1, 0, 0]
    assert remove_duplicates(a) == 3
    assert a[:3] == [-3, -1, 0]
    # (!) вырожденные
    assert remove_duplicates([]) == 0        # отсюда проверка if not nums
    assert remove_duplicates([1]) == 1


test_two_sum_sorted()
