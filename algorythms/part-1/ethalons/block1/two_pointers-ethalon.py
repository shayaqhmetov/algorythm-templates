# two_sum_sorted — LeetCode 167, Two Sum II
# ФОРМА А: указатели с двух концов, идут навстречу
#
# УСЛОВИЕ
#     Дано: ОТСОРТИРОВАННЫЙ массив и число target.
#     Найти: индексы двух элементов, дающих в сумме target.
#            Если пары нет — пустой список.
#
# ПРИМЕР
#     nums = [2, 7, 11, 15], target = 9  -> [0, 1]
#
#     [ 2,  7, 11, 15 ]
#       L           R     2 + 15 = 17 — много, двигаем R влево
#     [ 2,  7, 11, 15 ]
#       L       R         2 + 11 = 13 — много, двигаем R влево
#     [ 2,  7, 11, 15 ]
#       L   R             2 +  7 =  9 — нашли
#
# ЛОГИКА В ОДНУ СТРОКУ
#     сумма великовата -> правый влево (нужен элемент поменьше)
#     сумма маловата   -> левый вправо (нужен элемент побольше)
#
# ПОЧЕМУ ЭТО ЗАКОННО (тут вся суть)
#     Когда 2 + 15 оказалось много, мы выкинули не одну пару (2,15),
#     а ВСЕ пары с пятнадцаткой. Потому что 2 — самый маленький элемент,
#     и с любым другим 15 даст ещё больше.
#     Раз уж с минимальным перебор — 15 не подходит никому.
#
#     Это та же монотонность, что в бинарном поиске: отсортированность
#     даёт право выкидывать целые пласты не глядя.
#     Массив не отсортирован — форма А неприменима, нужен словарь.
#
# Сложность: O(n) времени, O(1) памяти.
# =============================================================================

def two_sum_sorted(nums, target):
    left, right = 0, len(nums) - 1

    while left < right:
        s = nums[left] + nums[right]
        if s == target:
            return [left, right]
        if s < target:
            left += 1        # мало — нужен элемент побольше
        else:
            right -= 1       # много — нужен поменьше

    return []


# =============================================================================
# is_palindrome
# ФОРМА А: тот же каркас, но БЕЗ сортировки
#
# УСЛОВИЕ
#     Проверить, читается ли строка одинаково слева направо и справа налево.
#
# ПРИМЕР
#     "abcba" -> True
#       L   R    'a' == 'a', сходимся
#        L R     'b' == 'b', сходимся
#         LR     left < right больше не выполняется, цикл кончился -> True
#
#     "abca" -> False ('a' vs 'a' ок, потом 'b' vs 'c' — не сошлось)
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Тот же каркас формы А, но сортировка тут не нужна: мы не ищем пару
#     по значению, а проверяем симметрию.
#     Показывает, что форма А — это не только "two sum".
#
# Замечание про цикл: while left < right, а не <=.
# При нечётной длине средний символ сравнивать сам с собой не нужно.
# =============================================================================

def is_palindrome(s):
    left, right = 0, len(s) - 1

    while left < right:
        if s[left] != s[right]:
            return False
        left += 1
        right -= 1

    return True


