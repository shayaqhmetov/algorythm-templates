# move_zeroes — LeetCode 283, Move Zeroes
# ФОРМА Б: догоняющие указатели, идут в одну сторону
#
# УСЛОВИЕ
#     Дано: массив.
#     Сделать: сдвинуть все ненулевые элементы влево, СОХРАНИВ их порядок,
#              нули — в конец. НА МЕСТЕ, без нового массива.
#
# ПРИМЕР
#     nums = [0, 1, 0, 3, 12]  ->  [1, 3, 12, 0, 0]
#
#     slow — КУДА писать, fast — ЧТО читать
#
#     fast=0: nums[0]=0   — ноль, пропускаем
#     fast=1: nums[1]=1   — пишем в slow=0, slow -> 1
#     fast=2: nums[2]=0   — пропускаем
#     fast=3: nums[3]=3   — пишем в slow=1, slow -> 2
#     fast=4: nums[4]=12  — пишем в slow=2, slow -> 3
#
#     получилось [1, 3, 12, ...] — хвост с позиции slow дозаполняем нулями
#
# РОЛИ УКАЗАТЕЛЕЙ (это и есть шаблон)
#     fast ЧИТАЕТ  — идёт всегда, по всем элементам без исключений.
#     slow ПИШЕТ   — двигается только когда что-то записали.
#     slow всегда показывает границу уже обработанной части.
#
# Сложность: O(n) времени, O(1) памяти.
# =============================================================================

def move_zeroes(nums):
    slow = 0

    for fast in range(len(nums)):
        if nums[fast] != 0:               # элемент нужен — записываем
            nums[slow] = nums[fast]
            slow += 1

    for i in range(slow, len(nums)):      # хвост — нулями
        nums[i] = 0

    return nums


