# find_min_rotated — LeetCode 153, Find Minimum in Rotated Sorted Array
# ВАРИАНТ Г: массив не отсортирован, а предикат всё равно монотонен
#
# УСЛОВИЕ
#     Дано: массив РАЗЛИЧНЫХ чисел, который был отсортирован по возрастанию,
#           а потом циклически сдвинут (возможно, на ноль позиций).
#           Массив не пуст.
#     Вернуть: минимальный элемент. За O(log n), проход циклом не считается.
#
# ПРИМЕР
#     nums = [4, 5, 6, 7, 0, 1, 2]  ->  0
#
#     Массив — это два возрастающих куска, и весь правый меньше всего левого:
#
#         4 5 6 7 | 0 1 2
#         левый   | правый
#
#     nums[i] <= nums[-1]:   F F F F T T T
#                                    ^ первое T — начало правого куска, минимум
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Она отучает от мысли "бинарный поиск — это про отсортированный массив".
#     Сортировки здесь нет, а бинарный поиск есть, потому что требование
#     другое: МОНОТОННЫЙ ПРЕДИКАТ. Нашёл вопрос, на который ответ идёт
#     F F F T T T, — дальше работает тот же bs без единой правки.
#
# ПОЧЕМУ СРАВНИВАЕМ С ПОСЛЕДНИМ, А НЕ С ПЕРВЫМ
#     Последний элемент всегда лежит в правом куске, поэтому хотя бы одно
#     True есть гарантированно, и граница не уедет за конец.
#     С первым элементом (nums[i] < nums[0]) всё ломается на массиве без
#     сдвига: [1, 2, 3] даёт F F F, bs возвращает 3, и nums[3] — IndexError.
#
# ПОЧЕМУ <=, А НЕ <
#     Сам последний элемент обязан дать True: nums[-1] <= nums[-1].
#     Со строгим знаком массив из одного элемента даёт F, и граница
#     опять уезжает за конец.
# =============================================================================

def find_min_rotated(nums):
    # правый кусок — всё, что не больше последнего элемента
    i = bs(0, len(nums), lambda i: nums[i] <= nums[-1])
    return nums[i]                       # граница — индекс, просят значение


# =============================================================================
# ТЕСТЫ
# Помеченные (!) — ловушки. Кривая версия проходит простые тесты
# и падает именно на них.
# =============================================================================

def test_bs():
    a = [1, 3, 3, 5, 7]
    # базовый: первая из двух троек
    assert bs(0, len(a), lambda i: a[i] >= 3) == 1
    assert bs(0, len(a), lambda i: a[i] >= 5) == 3
    # (!) истинных нет вообще — граница уезжает за конец, это не ошибка
    assert bs(0, len(a), lambda i: a[i] > 9) == 5
    # (!) всё истинно — ответ самый левый
    assert bs(0, len(a), lambda i: a[i] >= 0) == 0
    # строгое сравнение сдвигает границу за дубликаты
    assert bs(0, len(a), lambda i: a[i] > 3) == 3
    # (!) пустой отрезок — цикл не выполнится ни разу
    assert bs(0, 0, lambda i: True) == 0
    # отрезок из одного элемента, обе ветки
    assert bs(0, 1, lambda i: a[i] >= 1) == 0
    assert bs(0, 1, lambda i: a[i] >= 2) == 1
    # (!) диапазон не с нуля — bs не знает про массивы
    assert bs(5, 10, lambda x: x >= 8) == 8
    # (!) ответ ровно в mid — ловит hi = mid - 1 вместо hi = mid
    assert bs(0, 3, lambda i: [1, 3, 5][i] >= 3) == 1


def test_search_range():
    # базовый
    assert search_range([5, 7, 7, 8, 8, 10], 8) == [3, 4]
    # (!) числа нет, но граница попадает внутрь массива
    assert search_range([5, 7, 7, 8, 8, 10], 6) == [-1, -1]
    # (!) число больше всех — граница за концом
    assert search_range([5, 7, 7, 8, 8, 10], 11) == [-1, -1]
    assert search_range([5, 7, 7, 8, 8, 10], 4) == [-1, -1]
    # (!) весь массив состоит из target
    assert search_range([2, 2, 2], 2) == [0, 2]
    # на краях
    assert search_range([1, 2, 3], 1) == [0, 0]
    assert search_range([1, 2, 3], 3) == [2, 2]
    # (!) вырожденные
    assert search_range([], 0) == [-1, -1]
    assert search_range([1], 1) == [0, 0]
    assert search_range([1], 2) == [-1, -1]
    # отрицательные
    assert search_range([-5, -5, -1, 0], -5) == [0, 1]


def test_min_eating_speed():
    # базовый
    assert min_eating_speed([3, 6, 7, 11], 8) == 4
    # (!) часов ровно столько же, сколько куч — быстрее max не нужно
    assert min_eating_speed([30, 11, 23, 4, 20], 5) == 30
    # часов больше — можно медленнее
    assert min_eating_speed([30, 11, 23, 4, 20], 6) == 23
    # (!) времени вагон — ответ 1, левая граница диапазона
    assert min_eating_speed([1, 1, 1, 1], 4) == 1
    assert min_eating_speed([312884470], 968709470) == 1
    # (!) одна огромная куча — проверяет ceil, а не деление вниз
    assert min_eating_speed([1000000000], 2) == 500000000
    # вырожденный вход
    assert min_eating_speed([1], 1) == 1
    assert min_eating_speed([5], 2) == 3


def test_find_min_rotated():
    # базовый
    assert find_min_rotated([4, 5, 6, 7, 0, 1, 2]) == 0
    assert find_min_rotated([3, 4, 5, 1, 2]) == 1
    # (!) сдвига нет — ловит сравнение с первым элементом вместо последнего
    assert find_min_rotated([1, 2, 3]) == 1
    assert find_min_rotated([11, 13, 15, 17]) == 11
    # (!) один элемент — ловит строгий знак в предикате
    assert find_min_rotated([7]) == 7
    # (!) два элемента, оба порядка
    assert find_min_rotated([2, 1]) == 1
    assert find_min_rotated([1, 2]) == 1
    # (!) минимум на последнем месте
    assert find_min_rotated([2, 3, 4, 5, 1]) == 1
    # минимум сразу за первым
    assert find_min_rotated([5, 1, 2, 3, 4]) == 1
    # отрицательные
    assert find_min_rotated([0, 3, -5, -2]) == -5


test_bs()
test_search_range()
test_min_eating_speed()
test_find_min_rotated()
