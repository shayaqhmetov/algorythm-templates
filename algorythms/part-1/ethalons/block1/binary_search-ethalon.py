"""
ШАБЛОН 1 — БИНАРНЫЙ ПОИСК ПО ГРАНИЦЕ (lower_bound)

КОГДА ПРИМЕНЯТЬ
    Пространство ответов упорядочено, и есть предикат ok(x), который
    переключается ровно один раз: False False False True True True.
    Ищем ПЕРВОЕ True — границу, а не конкретное значение.
    Слова-маркеры: "отсортированный массив", "первое/последнее вхождение",
    "минимальная скорость / размер, при которой всё ещё успеваем",
    "минимизировать максимум", "максимизировать минимум".

ПОЧЕМУ ГРАНИЦА, А НЕ ПОИСК ПО ==
    Поиск по равенству разваливается на дубликатах (какое из трёх троек
    вернуть?) и требует отдельной ветки "не найдено".
    Форма lower_bound единообразна: одна и та же функция, меняется
    только предикат. Все задачи ниже — это она с разной начинкой.

ГАРАНТИЯ, БЕЗ КОТОРОЙ НИЧЕГО НЕ РАБОТАЕТ
    Предикат обязан быть МОНОТОННЫМ: если ok(i) истинно, то ok(i+1)
    тоже истинно. Не монотонен — бинарный поиск неприменим,
    выкидывать половину не за что.

СКЕЛЕТ (это и есть то, что заучивается)

    def bs(lo, hi, ok):            # ищем в ПОЛУИНТЕРВАЛЕ [lo, hi)
        while lo < hi:
            mid = lo + (hi - lo) // 2
            if ok(mid):
                hi = mid           # mid может быть ответом — не отбрасываем
            else:
                lo = mid + 1       # mid точно не ответ — отбрасываем
        return lo                  # первое True; hi, если True нет вовсе

ЧЕТЫРЕ МЕСТА, ГДЕ ОШИБАЮТСЯ

    1. hi = mid, но lo = mid + 1. Асимметрия не случайна.
       При ok(mid) истинном mid — кандидат в ответ, выбрасывать его нельзя.
       При ложном mid заведомо не ответ, поэтому +1.
       Написал hi = mid - 1 — потерял ответ и не заметил.

    2. Полуинтервал [lo, hi): hi — это граница ЗА последним элементом,
       то есть len(a), а не len(a) - 1.
       Тогда "ничего не подошло" возвращается само собой как hi,
       и отдельной ветки "не найдено" не нужно.

    3. Цикл while lo < hi, а не <=. С полуинтервалом lo == hi означает
       "отрезок пуст, ответ найден". С <= будет вечный цикл.

    4. Возвращается ИНДЕКС ГРАНИЦЫ, а не значение. Если нужен сам элемент,
       после bs обязательно проверь lo < len(a) and a[lo] == target —
       граница может указывать за конец массива или на другое число.

ПОЧЕМУ ЦИКЛ ВСЕГДА ЗАКАНЧИВАЕТСЯ
    При lo < hi всегда mid < hi. Значит ветка hi = mid строго уменьшает hi,
    а ветка lo = mid + 1 строго увеличивает lo. Отрезок сжимается каждый шаг.

ТРИ ВАРИАНТА, КОТОРЫЕ НАДО РАЗЛИЧАТЬ
    A) сам скелет                — bs               (граница по предикату)
    Б) первое и последнее вхождение — search_range  (два вызова bs)
    В) поиск ПО ОТВЕТУ           — min_eating_speed (диапазон — не массив)

ПОРЯДОК ДРИЛЛА (5 минут)
    В сессию берёшь ОДНУ функцию. Читаешь блок над ней в -drill.py как
    задание, пишешь тело, гоняешь её тесты, сверяешь с этим файлом.
    Ротация: 1) bs  2) search_range  3) min_eating_speed  4) с начала.
    bs пишется каждый раз — на нём стоят обе остальные.

ПРИЗНАК, ЧТО ШАБЛОН СЕЛ
    Четыре строки — while lo < hi, mid, hi = mid, lo = mid + 1 — выходят
    подряд без пауз, а думаешь только про то, что подставить в ok.
"""


# =============================================================================
# bs — сам скелет, lower_bound
# ВАРИАНТ A: граница по монотонному предикату
#
# УСЛОВИЕ
#     Дано: полуинтервал [lo, hi) и монотонный предикат ok.
#     Вернуть: наименьшее x из [lo, hi), для которого ok(x) истинно.
#              Если истинного нет ни одного — вернуть hi.
#
# ПРИМЕР
#     a = [1, 3, 3, 5, 7]
#     bs(0, 5, lambda i: a[i] >= 3) -> 1
#
#     ok по индексам:  F  T  T  T  T
#     индексы:         0  1  2  3  4
#                         ^ первое T
#
#     lo=0 hi=5  mid=2  a[2]=3 >= 3 -> T -> hi=2
#     lo=0 hi=2  mid=1  a[1]=3 >= 3 -> T -> hi=1
#     lo=0 hi=1  mid=0  a[0]=1 >= 3 -> F -> lo=1
#     lo == hi -> вернули 1
#
# ЛОВУШКА С ДУБЛИКАТАМИ
#     Троек в массиве две, и ответ ровно один — ПЕРВАЯ.
#     Это и есть причина, по которой при ok(mid) мы пишем hi = mid,
#     а не выходим сразу: слева может быть ещё одна тройка.
# =============================================================================

def bs(lo, hi, ok):
    while lo < hi:
        mid = lo + (hi - lo) // 2
        if ok(mid):
            hi = mid                 # mid — кандидат, не отбрасываем
        else:
            lo = mid + 1             # mid точно не ответ
    return lo


# =============================================================================
# search_range — LeetCode 34, Find First and Last Position
# ВАРИАНТ Б: две границы одним и тем же скелетом
#
# УСЛОВИЕ
#     Дано: ОТСОРТИРОВАННЫЙ массив и число target.
#     Вернуть: [первый индекс target, последний индекс target].
#              Если числа нет — [-1, -1].
#
# ПРИМЕР
#     nums = [5, 7, 7, 8, 8, 10], target = 8  -> [3, 4]
#
#     >= 8 :  F F F T T T   первое T = 3   -> левая граница
#     >  8 :  F F F F F T   первое T = 5   -> за последней восьмёркой
#     последний индекс = 5 - 1 = 4
#
# ИДЕЯ
#     Отдельного алгоритма для "последнего вхождения" не существует.
#     Последнее вхождение — это ПЕРВОЕ, что строго больше, минус один.
#     Меняется один символ в предикате: >= на >.
#
# ПОЧЕМУ НУЖНА ПРОВЕРКА ПОСЛЕ ПЕРВОГО ВЫЗОВА
#     bs всегда что-то возвращает, даже если target в массиве нет.
#     lo == len(nums) — граница уехала за конец,
#     nums[lo] != target — на границе стоит другое число.
#     Обе ситуации значат "не найдено", и обе ловятся одной строкой.
# =============================================================================

def search_range(nums, target):
    n = len(nums)
    left = bs(0, n, lambda i: nums[i] >= target)

    if left == n or nums[left] != target:      # граница есть, числа нет
        return [-1, -1]

    right = bs(0, n, lambda i: nums[i] > target) - 1
    return [left, right]


# =============================================================================
# min_eating_speed — LeetCode 875, Koko Eating Bananas
# ВАРИАНТ В: бинарный поиск ПО ОТВЕТУ
#
# УСЛОВИЕ
#     Дано: piles — кучи бананов, h — часов до прихода охраны.
#           За час съедается не больше speed бананов и только из одной кучи
#           (куча меньше speed — час всё равно потрачен целиком).
#     Вернуть: минимальную целую speed, при которой успеваем за h часов.
#
# ПРИМЕР
#     piles = [3, 6, 7, 11], h = 8  -> 4
#
#     speed=3: 1 + 2 + 3 + 4 = 10 часов — не успели
#     speed=4: 1 + 2 + 2 + 3 =  8 часов — успели, и меньше уже нельзя
#
# ЗАЧЕМ ЭТА ФУНКЦИЯ В ФАЙЛЕ
#     Здесь НЕТ отсортированного массива, по которому идёт поиск.
#     Ищем по диапазону ВОЗМОЖНЫХ ОТВЕТОВ: от 1 до max(piles).
#     Это главный переход в шаблоне: как только видишь "минимальное X,
#     при котором условие выполняется" — ищи границу по ответу.
#
# ГДЕ ЗДЕСЬ МОНОТОННОСТЬ
#     Успели при скорости s -> успеем и при любой большей.
#     Значит ok(s) = "успеваем за h" даёт F F F T T T. Это и есть право
#     выкидывать половину.
#
# ГРАНИЦЫ ДИАПАЗОНА
#     lo = 1  — скорость 0 бессмысленна и даёт деление на ноль.
#     hi = max(piles) + 1 — при скорости max(piles) каждая куча съедается
#     за час, быстрее уже не станет. Плюс один, потому что полуинтервал.
#
# ЧАСЫ СЧИТАЮТСЯ ВВЕРХ
#     (p + s - 1) // s — это ceil(p / s) целыми числами.
#     Обычное деление округлит вниз, и ответ окажется заниженным.
# =============================================================================

def min_eating_speed(piles, h):
    def ok(speed):
        hours = sum((p + speed - 1) // speed for p in piles)
        return hours <= h

    return bs(1, max(piles) + 1, ok)


# =============================================================================
# ТЕСТЫ
# Помеченные (!) — ловушки. Кривая версия проходит простые тесты
# и падает именно на них.
# =============================================================================

def test_bs():
    a = [1, 3, 3, 5, 7]
    # базовый: первая из двух троек
    assert bs(0, len(a), lambda i: a[i] >= 3) == 1
    assert bs(0, len(a), lambda i: a[i] >= 5) == 3
    # (!) истинных нет вообще — граница уезжает за конец, это не ошибка
    assert bs(0, len(a), lambda i: a[i] > 9) == 5
    # (!) всё истинно — ответ самый левый
    assert bs(0, len(a), lambda i: a[i] >= 0) == 0
    # строгое сравнение сдвигает границу за дубликаты
    assert bs(0, len(a), lambda i: a[i] > 3) == 3
    # (!) пустой отрезок — цикл не выполнится ни разу
    assert bs(0, 0, lambda i: True) == 0
    # отрезок из одного элемента, обе ветки
    assert bs(0, 1, lambda i: a[i] >= 1) == 0
    assert bs(0, 1, lambda i: a[i] >= 2) == 1
    # (!) диапазон не с нуля — bs не знает про массивы
    assert bs(5, 10, lambda x: x >= 8) == 8
    # (!) ответ ровно в mid — ловит hi = mid - 1 вместо hi = mid
    assert bs(0, 3, lambda i: [1, 3, 5][i] >= 3) == 1


def test_search_range():
    # базовый
    assert search_range([5, 7, 7, 8, 8, 10], 8) == [3, 4]
    # (!) числа нет, но граница попадает внутрь массива
    assert search_range([5, 7, 7, 8, 8, 10], 6) == [-1, -1]
    # (!) число больше всех — граница за концом
    assert search_range([5, 7, 7, 8, 8, 10], 11) == [-1, -1]
    assert search_range([5, 7, 7, 8, 8, 10], 4) == [-1, -1]
    # (!) весь массив состоит из target
    assert search_range([2, 2, 2], 2) == [0, 2]
    # на краях
    assert search_range([1, 2, 3], 1) == [0, 0]
    assert search_range([1, 2, 3], 3) == [2, 2]
    # (!) вырожденные
    assert search_range([], 0) == [-1, -1]
    assert search_range([1], 1) == [0, 0]
    assert search_range([1], 2) == [-1, -1]
    # отрицательные
    assert search_range([-5, -5, -1, 0], -5) == [0, 1]


def test_min_eating_speed():
    # базовый
    assert min_eating_speed([3, 6, 7, 11], 8) == 4
    # (!) часов ровно столько же, сколько куч — быстрее max не нужно
    assert min_eating_speed([30, 11, 23, 4, 20], 5) == 30
    # часов больше — можно медленнее
    assert min_eating_speed([30, 11, 23, 4, 20], 6) == 23
    # (!) времени вагон — ответ 1, левая граница диапазона
    assert min_eating_speed([1, 1, 1, 1], 4) == 1
    assert min_eating_speed([312884470], 968709470) == 1
    # (!) одна огромная куча — проверяет ceil, а не деление вниз
    assert min_eating_speed([1000000000], 2) == 500000000
    # вырожденный вход
    assert min_eating_speed([1], 1) == 1
    assert min_eating_speed([5], 2) == 3


test_bs()
test_search_range()
test_min_eating_speed()
print("ok — binary_search, все тесты прошли")
