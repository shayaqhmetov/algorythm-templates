def test_climb_stairs():
    # базовые
    assert climb_stairs(1) == 1
    assert climb_stairs(2) == 2
    assert climb_stairs(3) == 3
    assert climb_stairs(4) == 5
    assert climb_stairs(5) == 8
    # (!) ноль ступеней — один способ, а не ноль
    assert climb_stairs(0) == 1
    # (!) большое n — без memo это зависнет, с memo мгновенно
    assert climb_stairs(45) == 1836311903
    assert climb_stairs(10) == 89


def test_coin_change():
    # базовый
    assert coin_change([1, 2, 5], 11) == 3
    # (!) набрать нельзя
    assert coin_change([2], 3) == -1
    assert coin_change([7], 3) == -1
    # (!) нулевая сумма — ноль монет, а не -1
    assert coin_change([1], 0) == 0
    assert coin_change([], 0) == 0
    # (!) монет нет, а сумма есть
    assert coin_change([], 5) == -1
    # (!) жадность здесь ломается: 3+3 лучше, чем 4+1+1
    assert coin_change([1, 3, 4], 6) == 2
    # ровно одна монета
    assert coin_change([5], 5) == 1
    assert coin_change([1], 2) == 2
    # (!) сумма большая, монеты крупные — проверяет, что кэш реально работает
    assert coin_change([186, 419, 83, 408], 6249) == 20
    assert coin_change([2, 5, 10, 1], 27) == 4


def test_lcs():
    # базовый
    assert lcs("abcde", "ace") == 3
    # (!) общего нет вовсе
    assert lcs("abc", "def") == 0
    # строки совпадают целиком
    assert lcs("abc", "abc") == 3
    # (!) пустые строки — база рекурсии
    assert lcs("", "") == 0
    assert lcs("a", "") == 0
    assert lcs("", "a") == 0
    # (!) подпоследовательность, а не подстрока — символы идут вразбивку
    assert lcs("abcba", "abcbcba") == 5
    assert lcs("bl", "yby") == 1
    # (!) длина ответа не больше короткой строки
    assert lcs("aaa", "aa") == 2
    # разной длины и без явной структуры
    assert lcs("bsbininm", "jmjkbkjkv") == 1
    assert lcs("oxcpqrsvwf", "shmtulqrypy") == 2
    assert lcs("ezupkr", "ubmrapg") == 2


def test_house_robber():
    # базовый
    assert house_robber([1, 2, 3, 1]) == 4
    assert house_robber([2, 7, 9, 3, 1]) == 12
    # (!) выгодно пропустить ДВА дома подряд — ловит "чётные или нечётные"
    assert house_robber([2, 1, 1, 2]) == 4
    # (!) вырожденные
    assert house_robber([]) == 0
    assert house_robber([5]) == 5
    # (!) два дома — берём больший, каким бы по счёту он ни был
    assert house_robber([5, 1]) == 5
    assert house_robber([1, 5]) == 5
    # (!) одни нули — ноль тоже законный ответ и обязан кэшироваться
    assert house_robber([0, 0, 0]) == 0
    # один дом дороже обоих соседей вместе
    assert house_robber([1, 9, 1]) == 9
    # (!) длинная улица — без memo это не досчитается, сверяем с циклом
    big = [(i * 7) % 11 for i in range(80)]
    prev = best = 0
    for x in big:
        prev, best = best, max(best, prev + x)
    assert house_robber(big) == best


