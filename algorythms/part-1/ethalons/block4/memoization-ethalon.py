# lcs — LeetCode 1143, Longest Common Subsequence
# ВАРИАНТ В: состояние из ДВУХ параметров
#
# УСЛОВИЕ
#     Дано: две строки.
#     Вернуть: длину самой длинной общей ПОДПОСЛЕДОВАТЕЛЬНОСТИ —
#              символы идут в том же порядке, но не обязательно подряд.
#
# ПРИМЕР
#     "abcde", "ace"  ->  3   ("ace")
#     "abc", "def"    ->  0
#
# СОСТОЯНИЕ
#     go(i, j) — ответ для хвостов a[i:] и b[j:].
#     Ключ memo — ПАРА (i, j). Это главное, ради чего функция в файле:
#     как только состояние перестаёт быть одним числом, ключом становится
#     кортеж, и забыть в нём второй параметр — типовая ошибка.
#
# РЕКУРРЕНТНОЕ СООТНОШЕНИЕ
#     a[i] == b[j]  ->  1 + go(i+1, j+1)      символ берём в ответ
#     иначе         ->  max(go(i+1, j), go(i, j+1))
#                       пропускаем либо символ из a, либо из b, и берём
#                       лучшее из двух вариантов
#
# ПОЧЕМУ ПРИ РАВЕНСТВЕ НЕ НАДО ПЕРЕБИРАТЬ ОСТАЛЬНОЕ
#     Если символы совпали, всегда можно взять их в ответ — хуже от этого
#     не станет. Доказывается обменным рассуждением, и на интервью это
#     стоит проговорить, а не молча написать.
#
# СКОЛЬКО ЗДЕСЬ СОСТОЯНИЙ
#     len(a) x len(b) — отсюда и сложность O(n*m).
#     Без memo было бы 2^(n+m): для строк по 20 символов разница
#     между мгновением и вечностью.
# =============================================================================

def lcs(a, b):
    memo = {}

    def go(i, j):
        if i == len(a) or j == len(b):   # база: строка кончилась
            return 0
        if (i, j) in memo:               # ключ — ПАРА, а не одно число
            return memo[(i, j)]

        if a[i] == b[j]:
            res = 1 + go(i + 1, j + 1)   # совпало — берём
        else:
            res = max(go(i + 1, j), go(i, j + 1))   # пропускаем одно из двух

        memo[(i, j)] = res
        return res

    return go(0, 0)


