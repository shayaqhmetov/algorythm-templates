# =============================================================================
# climb_stairs — LeetCode 70, Climbing Stairs
# ВАРИАНТ A: состояние — одно число, ответы складываются
#
# УСЛОВИЕ
#     Дано: лестница из n ступеней. За шаг поднимаемся на 1 или на 2.
#     Вернуть: число различных способов подняться наверх.
#              n = 0 — один способ (никуда не идти).
#
# ПРИМЕР
#     n = 4  ->  5
#     1+1+1+1, 1+1+2, 1+2+1, 2+1+1, 2+2
#
# СОСТОЯНИЕ
#     go(k) — сколько способов подняться на k ступеней.
#     Один параметр, он же ключ memo.
#
# РЕКУРРЕНТНОЕ СООТНОШЕНИЕ
#     На верхнюю ступеньку мы попали либо с k-1, либо с k-2.
#     Эти пути не пересекаются и покрывают все варианты, значит
#         go(k) = go(k-1) + go(k-2)
#     Это Фибоначчи, но выводить его надо не по памяти, а вот этим
#     рассуждением: "откуда мы сюда пришли".
#
# ЗАЧЕМ ЗДЕСЬ ВООБЩЕ memo
#     Без него go(45) считается минуты: одно и то же go(30) вычисляется
#     миллионы раз. С memo — 45 вычислений. Это самая наглядная
#     демонстрация всего шаблона, ради неё функция и стоит первой.
#
# БАЗА
#     go(0) = 1 и go(1) = 1. Ноль способов было бы неверно: пустой путь —
#     это тоже способ, иначе вся сумма схлопнется в ноль.
# =============================================================================

def climb_stairs(n):
    memo = {}

    def go(k):
        if k <= 1:                       # база: 0 и 1 ступени — один способ
            return 1
        if k in memo:                    # уже считали
            return memo[k]

        memo[k] = go(k - 1) + go(k - 2)  # пришли либо оттуда, либо оттуда
        return memo[k]

    return go(n)


# =============================================================================
# coin_change — LeetCode 322, Coin Change
# ВАРИАНТ Б: минимум + отдельное "невозможно"
#
# УСЛОВИЕ
#     Дано: номиналы монет (каждую можно брать сколько угодно раз)
#           и сумма amount.
#     Вернуть: минимальное число монет, дающих ровно amount.
#              Набрать нельзя — вернуть -1. amount = 0 — ноль монет.
#
# ПРИМЕР
#     coins = [1, 2, 5], amount = 11  ->  3    (5 + 5 + 1)
#
#     go(11) = 1 + min(go(10), go(9), go(6))
#     go(6)  = 1 + min(go(5),  go(4), go(1))
#     go(5)  = 1 + min(go(4),  go(3), go(0)) = 1
#
# СОСТОЯНИЕ
#     go(rest) — минимум монет, чтобы добрать rest.
#     Считаем ОСТАТОК, а не набранную сумму: тогда база это rest == 0,
#     и лишний параметр не нужен.
#
# ПОЧЕМУ ЖАДНОСТЬ ЗДЕСЬ НЕ РАБОТАЕТ
#     "Бери самую крупную монету" ломается на coins = [1, 3, 4], amount = 6:
#     жадно 4+1+1 = три монеты, правильно 3+3 = две.
#     Это стандартный контрвопрос на интервью, ответ надо знать заранее.
#
# ЗАЧЕМ БЕСКОНЕЧНОСТЬ
#     "Невозможно" должно проигрывать любому числу в min и при этом
#     переживать +1. float('inf') делает и то и другое, а -1 в min
#     победил бы всех и молча испортил ответ.
#     Минус единица появляется ровно один раз — в самом конце.
#
# ЧТО ЛЕГКО ЗАБЫТЬ
#     Записывать в memo и бесконечность тоже: безнадёжные остатки
#     иначе пересчитываются заново каждый раз.
# =============================================================================

def coin_change(coins, amount):
    memo = {}

    def go(rest):
        if rest == 0:                    # база: добрали
            return 0
        if rest < 0:                     # перебрали — тупик
            return float('inf')
        if rest in memo:
            return memo[rest]

        best = float('inf')
        for c in coins:
            best = min(best, go(rest - c) + 1)

        memo[rest] = best                # запоминаем и бесконечность тоже
        return best

    res = go(amount)
    return res if res != float('inf') else -1


