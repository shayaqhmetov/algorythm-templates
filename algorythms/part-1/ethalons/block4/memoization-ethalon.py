# house_robber — LeetCode 198, House Robber
# ВАРИАНТ Г: на каждом шаге выбор "взять или пропустить"
#
# УСЛОВИЕ
#     Дано: nums — сколько денег лежит в каждом доме на улице.
#           Два СОСЕДНИХ дома брать нельзя.
#     Вернуть: наибольшую сумму, которую можно унести.
#
# ПРИМЕР
#     [2, 7, 9, 3, 1]  ->  12    (дома 0, 2 и 4: 2 + 9 + 1)
#     [2, 1, 1, 2]     ->  4     (дома 0 и 3 — пропущено ДВА подряд)
#
# СОСТОЯНИЕ
#     go(i) — лучший улов, если в распоряжении дома с i-го до конца.
#     Одно число, как в climb_stairs. Что было левее i — неважно:
#     раз мы стоим на i, значит его брать уже можно.
#
# ЧТО ОТЛИЧАЕТСЯ ОТ ПЕРВЫХ ТРЁХ
#     В climb_stairs ответы детей складывались, в coin_change перебирались
#     все монеты. Здесь ветки ровно две, и каждая — решение про текущий дом:
#         взял        nums[i] + go(i + 2)    соседний пропускаю
#         пропустил   go(i + 1)              иду дальше
#     Ответ — максимум из двух. Эта пара "взял / пропустил" — самая частая
#     форма в динамике: рюкзак, акции, расписания — всё она.
#
# ПОЧЕМУ НЕ "ЧЁТНЫЕ ИЛИ НЕЧЁТНЫЕ"
#     Жадность через один дом ломается на [2, 1, 1, 2]: чётные дают 3,
#     нечётные 3, а правильный ответ 4. Иногда выгодно пропустить два подряд,
#     и перебор обеих веток это учитывает сам.
#
# БАЗА
#     i >= len(nums), а не ==. Из предпоследнего дома go(i + 2) прыгает
#     на одну позицию ЗА конец массива.
# =============================================================================

def house_robber(nums):
    memo = {}

    def go(i):                           # лучший улов с домов i..конец
        if i >= len(nums):               # база: >=, прыжок на 2 уходит за конец
            return 0
        if i in memo:
            return memo[i]

        take = nums[i] + go(i + 2)       # взял — соседний пропускаю
        skip = go(i + 1)                 # пропустил — иду дальше

        memo[i] = max(take, skip)
        return memo[i]

    return go(0)


