def test_prefix_sums():
    # базовый
    assert prefix_sums([2, 4, 1, 3]) == [0, 2, 6, 7, 10]
    # (!) длина на единицу больше, а первый элемент — ноль
    assert prefix_sums([]) == [0]
    assert prefix_sums([5]) == [0, 5]
    # (!) формула суммы отрезка: p[r + 1] - p[l]
    nums = [2, 4, 1, 3]
    p = prefix_sums(nums)
    assert p[3] - p[1] == 5                      # nums[1..2]
    assert p[1] - p[0] == 2                      # nums[0..0]
    assert p[len(nums)] - p[0] == sum(nums)      # весь массив
    # отрицательные и нули
    assert prefix_sums([-1, 1, -1]) == [0, -1, 0, -1]
    assert prefix_sums([0, 0]) == [0, 0, 0]
    # длинный вход — сверяем с честной суммой
    big = [(i * 7) % 13 - 6 for i in range(200)]
    p = prefix_sums(big)
    assert all(p[i] == sum(big[:i]) for i in range(0, 201, 25))


def test_subarray_sum_k():
    # базовый
    assert subarray_sum_k([1, 1, 1], 2) == 2
    assert subarray_sum_k([1, 2, 3], 3) == 2
    # (!) подмассив от самого начала — ловит забытый {0: 1}
    assert subarray_sum_k([1, 2], 1) == 1
    assert subarray_sum_k([3], 3) == 1
    # (!) отрицательные: окном такое не решается
    assert subarray_sum_k([1, -1, 0], 0) == 3
    assert subarray_sum_k([-1, -1, 1], 0) == 1
    # (!) k = 0 и нули — ловит перепутанный порядок в цикле
    assert subarray_sum_k([0, 0, 0], 0) == 6
    assert subarray_sum_k([1, 0, 1], 1) == 4
    # ничего не подходит
    assert subarray_sum_k([1, 2, 3], 100) == 0
    assert subarray_sum_k([], 0) == 0
    # длинный вход — сверяем с перебором всех подмассивов
    big = [(i * 7) % 5 - 2 for i in range(60)]
    naive = sum(1 for i in range(len(big)) for j in range(i, len(big))
                if sum(big[i:j + 1]) == 2)
    assert subarray_sum_k(big, 2) == naive


def test_product_except_self():
    # базовый
    assert product_except_self([1, 2, 3, 4]) == [24, 12, 8, 6]
    # (!) один ноль: везде ноль, кроме его собственного места
    assert product_except_self([-1, 1, 0, -3, 3]) == [0, 0, 9, 0, 0]
    # (!) два нуля — весь ответ нулевой
    assert product_except_self([0, 0, 3]) == [0, 0, 0]
    # (!) вырожденные
    assert product_except_self([]) == []
    assert product_except_self([5]) == [1]
    assert product_except_self([2, 3]) == [3, 2]
    # отрицательные и единицы
    assert product_except_self([-1, -2, -3]) == [6, 3, 2]
    assert product_except_self([1, 1, 1]) == [1, 1, 1]
    # (!) сверяем с честным перебором, где деление не нужно
    big = [(i % 5) - 2 or 3 for i in range(12)]
    naive = [
        [1 if j == i else big[j] for j in range(len(big))]
        for i in range(len(big))
    ]
    expected = []
    for row in naive:
        acc = 1
        for v in row:
            acc *= v
        expected.append(acc)
    assert product_except_self(big) == expected


def test_range_add():
    # базовый
    assert range_add(5, [[1, 3, 2], [2, 4, 3], [0, 2, -2]]) == [-2, 0, 3, 5, 3]
    # (!) отрезок до последнего индекса — ловит diff длины n
    assert range_add(3, [[0, 2, 5]]) == [5, 5, 5]
    assert range_add(1, [[0, 0, 7]]) == [7]
    # (!) отрезок из одной клетки — ловит отмену в r вместо r + 1
    assert range_add(3, [[1, 1, 4]]) == [0, 4, 0]
    # (!) операций нет — массив нулей нужной длины
    assert range_add(3, []) == [0, 0, 0]
    assert range_add(0, []) == []
    # (!) одинаковые отрезки складываются
    assert range_add(2, [[0, 1, 1], [0, 1, 1]]) == [2, 2]
    # (!) прибавка и отмена гасят друг друга
    assert range_add(3, [[0, 2, 5], [0, 2, -5]]) == [0, 0, 0]
    # края по отдельности, середина не тронута
    assert range_add(4, [[3, 3, 1], [0, 0, 1]]) == [1, 0, 0, 1]
    # вложенные отрезки
    assert range_add(5, [[0, 4, 1], [1, 3, 1], [2, 2, 1]]) == [1, 2, 3, 2, 1]


test_prefix_sums()
test_subarray_sum_k()
test_product_except_self()
test_range_add()
print("ok — prefix_sums, все тесты прошли")
